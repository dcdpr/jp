use super::*;

/// `2026-08-10T00:00:00Z`, the epoch the jp repository's own tickets count
/// from.
const JP_EPOCH_SECS: u64 = 1_786_320_000;

#[test]
fn an_epoch_starts_at_midnight_utc_of_its_day() {
    let epoch = Epoch::day_of(JP_EPOCH_SECS + 86_399).unwrap();

    assert_eq!(epoch.to_string(), "2026-08-10");
    assert_eq!(epoch.unix_seconds(), JP_EPOCH_SECS);
}

#[test]
fn the_next_day_is_a_different_epoch() {
    let epoch = Epoch::day_of(JP_EPOCH_SECS + 86_400).unwrap();

    assert_eq!(epoch.to_string(), "2026-08-11");
}

#[test]
fn render_writes_the_preamble_and_the_date() {
    let epoch = Epoch::day_of(JP_EPOCH_SECS).unwrap();

    assert_eq!(
        epoch.render(),
        "DO NOT EDIT THIS FILE! IT IS AUTO-GENERATED BY JP-TICKET\n2026-08-10\n"
    );
}

#[test]
fn a_rendered_epoch_reads_back() {
    let epoch = Epoch::day_of(JP_EPOCH_SECS).unwrap();

    assert_eq!(epoch.render().parse::<Epoch>(), Ok(epoch));
}

#[test]
fn a_bare_date_reads_without_a_preamble() {
    let epoch = "2026-08-10\n".parse::<Epoch>().unwrap();

    assert_eq!(epoch.unix_seconds(), JP_EPOCH_SECS);
}

#[test]
fn an_empty_file_holds_no_date() {
    assert_eq!(" \n\n".parse::<Epoch>(), Err(ParseError::EpochEmpty));
}

/// The date is read from the last line without looking at the rest, so a file
/// written under an older preamble still reads.
#[test]
fn the_preamble_wording_is_not_read() {
    let epoch = "# DO NOT EDIT\nanything at all\n2026-08-10\n".parse::<Epoch>();

    assert_eq!(epoch, Ok(Epoch::day_of(JP_EPOCH_SECS).unwrap()));
}

#[test]
fn trailing_blank_lines_are_skipped() {
    let epoch = "DO NOT EDIT THIS FILE! IT IS AUTO-GENERATED BY JP-TICKET\n2026-08-10\n\n  \n"
        .parse::<Epoch>();

    assert_eq!(epoch, Ok(Epoch::day_of(JP_EPOCH_SECS).unwrap()));
}

/// With the date line gone, the preamble is the last line, and is named as the
/// line that isn't a date.
#[test]
fn a_file_with_only_the_preamble_names_it() {
    assert_eq!(
        "DO NOT EDIT THIS FILE! IT IS AUTO-GENERATED BY JP-TICKET\n".parse::<Epoch>(),
        Err(ParseError::Epoch(
            "DO NOT EDIT THIS FILE! IT IS AUTO-GENERATED BY JP-TICKET".to_owned()
        ))
    );
}

#[test]
fn a_line_that_is_not_a_date_is_named() {
    assert_eq!(
        "DO NOT EDIT THIS FILE! IT IS AUTO-GENERATED BY JP-TICKET\n2026-08-10T00:00:00Z\n"
            .parse::<Epoch>(),
        Err(ParseError::Epoch("2026-08-10T00:00:00Z".to_owned()))
    );
}
