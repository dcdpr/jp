use camino_tempfile::Utf8TempDir;

use super::*;

/// A kind shaped like a wiki page.
#[derive(Debug)]
enum Page {}

impl Kind for Page {
    const PREFIX: char = 'W';
    const NOUN: &'static str = "wiki page";
    const WRITER: &'static str = "JP-WIKI";
}

/// `2026-08-10T00:00:00Z`.
const JP_EPOCH_SECS: u64 = 1_786_320_000;

fn id(bucket: u32, tail: u16) -> Id<Page> {
    Id::new(bucket, tail).unwrap()
}

/// Write an empty document file for `id`, as another checkout would have.
fn place(dir: &Utf8TempDir, id: Id<Page>, slug: &str) -> Utf8PathBuf {
    let path = dir.path().join(format!("{}{slug}.md", id.file_prefix()));
    fs::write(&path, "").unwrap();

    path
}

#[test]
fn list_is_ordered_by_id_and_skips_other_files() {
    let dir = Utf8TempDir::new().unwrap();
    let later = place(&dir, id(7, 1), "later");
    let earlier = place(&dir, id(7, 0), "earlier");
    for name in ["index.md", "notes.txt", "0005-legacy.md", ".order.json"] {
        fs::write(dir.path().join(name), "").unwrap();
    }

    let files = list::<Page>(dir.path()).unwrap();

    assert_eq!(files, [(id(7, 0), earlier), (id(7, 1), later)]);
}

#[test]
fn list_of_a_missing_directory_is_empty() {
    let dir = Utf8TempDir::new().unwrap();

    assert_eq!(list::<Page>(&dir.path().join("missing")).unwrap(), []);
}

#[test]
fn locate_finds_the_one_file_an_id_names() {
    let dir = Utf8TempDir::new().unwrap();
    let path = place(&dir, id(7, 0), "page");

    assert_eq!(locate(dir.path(), id(7, 0)).unwrap(), path);
    assert!(matches!(
        locate(dir.path(), id(7, 1)),
        Err(Error::NotFound(missing)) if missing == id(7, 1)
    ));
}

/// Two files claiming one id leaves every reference to it ambiguous, so a
/// lookup refuses rather than landing on whichever the directory yielded first.
#[test]
fn locate_refuses_an_id_two_files_claim() {
    let dir = Utf8TempDir::new().unwrap();
    let first = place(&dir, id(7, 0), "first");
    let second = place(&dir, id(7, 0), "second");

    let error = locate(dir.path(), id(7, 0)).unwrap_err();

    assert_eq!(
        error.to_string(),
        format!("W-0000700 is claimed by more than one file: {first}, {second}.")
    );
}

#[test]
fn duplicate_names_the_first_shared_id() {
    let dir = Utf8TempDir::new().unwrap();
    place(&dir, id(7, 0), "only");
    place(&dir, id(7, 1), "first");
    place(&dir, id(7, 1), "second");

    let files = list::<Page>(dir.path()).unwrap();

    assert!(matches!(
        duplicate(&files),
        Some(Error::Duplicate { id: shared, paths }) if shared == id(7, 1) && paths.len() == 2
    ));
    assert!(duplicate(&files[..2]).is_none());
}

/// A directory filing its first document starts its own clock, written with the
/// preamble of the tool its kind names.
#[test]
fn the_first_document_writes_an_epoch_naming_its_writer() {
    let dir = Utf8TempDir::new().unwrap();

    let (id, path) =
        create::<Page>(dir.path(), &Formatting::default(), "first", "# First\n").unwrap();

    let source = fs::read_to_string(dir.path().join(EPOCH_FILE)).unwrap();
    assert!(
        source.starts_with("DO NOT EDIT THIS FILE! IT IS AUTO-GENERATED BY JP-WIKI\n"),
        "{source}"
    );
    // One day holds 17,280 five-second buckets.
    assert!(id.bucket() < 17_280, "{id} sits in bucket {}", id.bucket());
    assert_eq!(fs::read_to_string(path).unwrap(), "# First\n");
}

#[test]
fn create_names_the_file_for_its_id_and_slug() {
    let dir = Utf8TempDir::new().unwrap();

    let (id, path) = create::<Page>(
        dir.path(),
        &Formatting::default(),
        "ubiquitous-language",
        "",
    )
    .unwrap();

    assert_eq!(
        path,
        dir.path()
            .join(format!("{}ubiquitous-language.md", id.file_prefix()))
    );
}

/// Documents created back to back land in one bucket, where the tail increments
/// rather than being redrawn.
#[test]
fn ids_created_in_sequence_stay_ordered() {
    let dir = Utf8TempDir::new().unwrap();

    let first = create::<Page>(dir.path(), &Formatting::default(), "first", "")
        .unwrap()
        .0;
    let second = create::<Page>(dir.path(), &Formatting::default(), "second", "")
        .unwrap()
        .0;

    assert!(first < second, "{first} !< {second}");
    // A run straddling a bucket boundary is still ordered, by the time
    // component instead.
    if first.bucket() == second.bucket() {
        assert_eq!(second.tail(), first.tail() + 1);
    }
}

#[test]
fn an_existing_epoch_is_kept() {
    let dir = Utf8TempDir::new().unwrap();
    fs::write(dir.path().join(EPOCH_FILE), "2026-08-10\n").unwrap();

    let epoch = establish_epoch::<Page>(dir.path()).unwrap();

    assert_eq!(epoch, Epoch::day_of(JP_EPOCH_SECS).unwrap());
    assert_eq!(
        fs::read_to_string(dir.path().join(EPOCH_FILE)).unwrap(),
        "2026-08-10\n"
    );
}

/// Documents with no epoch beside them can't take a fresh one: today's would
/// sort every new id below the ones already filed.
#[test]
fn documents_without_an_epoch_refuse_a_new_one() {
    let dir = Utf8TempDir::new().unwrap();
    place(&dir, id(7, 0), "page");

    let error = establish_epoch::<Page>(dir.path()).unwrap_err();

    assert!(matches!(error, Error::MissingEpoch(_)), "{error}");
    assert!(!dir.path().join(EPOCH_FILE).exists());
    assert_eq!(
        error.to_string(),
        format!(
            "{} is missing, so a new wiki page id can't be ordered against the existing ones. \
             Restore it from version control.",
            dir.path().join(EPOCH_FILE)
        )
    );
}

#[test]
fn a_malformed_epoch_is_named() {
    let dir = Utf8TempDir::new().unwrap();
    fs::write(dir.path().join(EPOCH_FILE), "yesterday\n").unwrap();

    let error = create::<Page>(dir.path(), &Formatting::default(), "first", "").unwrap_err();

    assert_eq!(
        error.to_string(),
        format!(
            "{}: `yesterday` is not an epoch date (try 2026-08-10).",
            dir.path().join(EPOCH_FILE)
        )
    );
}

#[test]
fn an_empty_directory_holds_no_epoch() {
    let dir = Utf8TempDir::new().unwrap();

    assert!(read_epoch::<Page>(dir.path()).unwrap().is_none());
    assert!(matches!(
        load_epoch::<Page>(dir.path()),
        Err(Error::MissingEpoch(_))
    ));
}

#[test]
fn buckets_count_from_the_epoch_given() {
    let epoch = Epoch::day_of(JP_EPOCH_SECS).unwrap();

    // Four days in: 345,600 seconds, at five seconds a bucket.
    assert_eq!(
        bucket_at::<Page>(epoch, JP_EPOCH_SECS + 345_600).unwrap(),
        69_120
    );
    assert!(matches!(
        bucket_at::<Page>(epoch, JP_EPOCH_SECS - 1),
        Err(Error::ClockBeforeEpoch(found)) if found == epoch
    ));
}

#[test]
fn allocation_continues_from_the_highest_tail_in_the_bucket() {
    let dir = Utf8TempDir::new().unwrap();
    place(&dir, id(7, 3), "a");
    place(&dir, id(7, 9), "b");
    place(&dir, id(8, 0), "later");

    assert_eq!(allocate_in::<Page>(dir.path(), 7).unwrap(), id(7, 10));
}

#[test]
fn a_full_bucket_spills_into_the_next() {
    let dir = Utf8TempDir::new().unwrap();
    place(&dir, id(7, TAIL_SPACE - 1), "last");

    assert_eq!(allocate_in::<Page>(dir.path(), 7).unwrap().bucket(), 8);
}

#[test]
fn slugs_are_lowercase_and_hyphenated() {
    assert_eq!(
        slug("Tool call header misaligned"),
        "tool-call-header-misaligned"
    );
    assert_eq!(slug("`jp query --new` panics!"), "jp-query-new-panics");
    assert_eq!(slug("  Spaced  out  "), "spaced-out");
    assert_eq!(slug("snake_case"), "snake_case");
    assert_eq!(slug("!!!"), "untitled");
    assert_eq!(slug(&"long ".repeat(20)).len(), 59);
}

#[test]
fn the_last_bucket_is_exhausted() {
    let dir = Utf8TempDir::new().unwrap();
    place(&dir, id(MAX_BUCKET - 1, TAIL_SPACE - 1), "last");

    assert!(matches!(
        allocate_in::<Page>(dir.path(), MAX_BUCKET - 1),
        Err(Error::Exhausted)
    ));
}
