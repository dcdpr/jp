#[test]
fn a_blob_is_named_by_its_hash_and_checked_when_read() {
    let dir = Utf8TempDir::new().unwrap();
    let blobs = Blobs {
        dir: dir.path().join(BLOB_DIR),
    };

    let name = blobs.put("text\n").unwrap();
    assert_eq!(name, hash("text\n"));
    assert_eq!(blobs.put("text\n").unwrap(), name);
    assert_eq!(blobs.get(&name).unwrap(), "text\n");

    fs::write(dir.path().join(BLOB_DIR).join(&name), "other\n").unwrap();
    assert_eq!(
        blobs.get(&name).unwrap_err(),
        format!(
            "{} doesn't hold what its name says; the review is damaged.",
            dir.path().join(BLOB_DIR).join(&name)
        )
    );
    assert_eq!(
        blobs.get("../review.json").unwrap_err(),
        "`../review.json` is not the name of a blob."
    );
}

#[test]
fn a_manifest_names_each_file_by_its_blob() {
    let contents = BTreeMap::from([
        ("a.md".to_owned(), Some("one\n".to_owned())),
        ("b.md".to_owned(), None),
    ]);

    assert_eq!(
        manifest(&contents),
        Files::from([
            ("a.md".to_owned(), Some(hash("one\n"))),
            ("b.md".to_owned(), None),
        ])
    );
    assert_eq!(
        hash(""),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );
}
