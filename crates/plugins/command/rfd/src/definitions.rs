//! Definitions for the tools this plugin serves.
//!
//! `jp rfd tools init` writes a starting set, one file per tool, for a project
//! to load and adjust; from then on the project owns them.
//! `jp rfd tools sync` writes the one part that mirrors configuration: the
//! categories, offered in the schemas of the tools that take one.
//! It owns a file of its own, [`SYNCED_FILE`], and rewrites it whole, so edits
//! to the definitions survive it.

use std::{
    fs::{self, OpenOptions},
    io::{self, Write as _},
};

use camino::Utf8Path;
use serde_json::Value;

use crate::Output;

/// The definitions `tools init` writes, by file name.
pub(crate) const DEFINITIONS: &[(&str, &str)] = &[
    ("list.toml", include_str!("../tools/list.toml")),
    ("show.toml", include_str!("../tools/show.toml")),
];

/// The file `tools sync` writes, inside the definitions directory.
pub(crate) const SYNCED_FILE: &str = "synced.toml";

/// The line a synced file opens with.
///
/// A file in its place without it was not written by `tools sync`, and is left
/// alone.
const SYNCED_HEADER: &str = "# Generated by `jp rfd tools sync`.";

/// What a synced file says about itself, below [`SYNCED_HEADER`].
const SYNCED_NOTES: &str = "\
#
# Mirrors the configured RFD categories into the schemas of the tools that take
# one, so the assistant is offered them rather than guessing. Run the command
# again after changing the categories or the tools: this file is rewritten
# whole, and edits to it are lost.
";

/// The plugin a tool's `source` has to name for the tool to be one of ours.
const PLUGIN: &str = "rfd";

/// The tools that take a category, by the name a `source` gives them.
const TAKES_A_CATEGORY: &[&str] = &["list"];

/// Write the starting definitions into `dir`, creating it if needed.
///
/// Refuses before writing anything when one of the files is already there.
pub(crate) fn init(dir: &Utf8Path) -> Result<Output, String> {
    let existing: Vec<String> = DEFINITIONS
        .iter()
        .map(|(name, _)| dir.join(name))
        .filter(|path| path.exists())
        .map(|path| path.to_string())
        .collect();
    if !existing.is_empty() {
        return Err(format!(
            "Refusing to overwrite {}. Move them aside first.",
            existing.join(", ")
        ));
    }

    fs::create_dir_all(dir).map_err(|error| format!("failed to create {dir}: {error}"))?;

    let mut text = String::new();
    for (name, content) in DEFINITIONS {
        let path = dir.join(name);
        // `create_new` rather than a plain write, so a file that appeared since
        // the check above is still not overwritten.
        OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
            .and_then(|mut file| file.write_all(content.as_bytes()))
            .map_err(|error| format!("failed to write {path}: {error}"))?;
        text.push_str(&format!("Wrote {path}\n"));
    }

    text.push_str(&format!(
        "Load the directory from the workspace configuration, then run `jp rfd tools sync {dir}` \
         to offer the categories.\n"
    ));

    Ok(text.into())
}

/// Write the categories into the schemas of the configured tools that take one,
/// as `dir`'s synced file.
///
/// Tools are found by their `source` in `config`, not by their key, so a tool
/// renamed in configuration still gets the categories under the name it has
/// there.
pub(crate) fn sync(
    dir: &Utf8Path,
    config: &Value,
    categories: &[String],
) -> Result<Output, String> {
    if !dir.is_dir() {
        return Err(format!("{dir} is not a directory."));
    }

    let path = dir.join(SYNCED_FILE);
    match fs::read_to_string(&path) {
        Ok(existing) if !existing.starts_with(SYNCED_HEADER) => {
            return Err(format!(
                "{path} was not written by `jp rfd tools sync`, so it is left alone. Move it \
                 aside first."
            ));
        }
        Ok(_) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(error) => return Err(format!("{path}: {error}")),
    }

    let keys: Vec<String> = served_tools(config)
        .into_iter()
        .filter(|(_, tool)| TAKES_A_CATEGORY.contains(&tool.as_str()))
        .map(|(key, _)| key)
        .collect();

    fs::write(&path, synced(&keys, categories))
        .map_err(|error| format!("failed to write {path}: {error}"))?;

    Ok(if keys.is_empty() {
        format!("Wrote {path}; no configured tool takes a category from `jp rfd`.\n")
    } else {
        format!("Wrote {path}, with categories for {}\n", keys.join(", "))
    }
    .into())
}

/// The configured tools this plugin serves, as `(key, tool)` pairs ordered by
/// key.
///
/// `tool` is the name the plugin knows it by: the last part of its `source`, or
/// its key when the source names only the plugin.
pub(crate) fn served_tools(config: &Value) -> Vec<(String, String)> {
    let Some(tools) = config
        .pointer("/conversation/tools")
        .and_then(Value::as_object)
    else {
        return vec![];
    };

    let mut served: Vec<(String, String)> = tools
        .iter()
        .filter_map(|(key, tool)| {
            let source = tool.get("source")?.as_str()?;
            let rest = source.strip_prefix("plugin.command.")?;
            let (plugin, name) = rest.split_once('.').unwrap_or((rest, key.as_str()));

            (plugin == PLUGIN).then(|| (key.clone(), name.to_owned()))
        })
        .collect();
    served.sort();

    served
}

/// Render the synced file for the tools keyed `keys`, each taking a category.
fn synced(keys: &[String], categories: &[String]) -> String {
    let mut out = format!("{SYNCED_HEADER}\n{SYNCED_NOTES}");

    for key in keys {
        out.push_str(&format!(
            "\n[conversation.tools.{}.parameters.category]\nenum = [\n",
            toml_key(key)
        ));
        for category in categories {
            out.push_str(&format!("  {},\n", toml_string(category)));
        }
        out.push_str("]\n");
    }

    out
}

/// A TOML key: bare when it can be, quoted otherwise.
fn toml_key(key: &str) -> String {
    let bare = !key.is_empty()
        && key
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-');

    if bare {
        key.to_owned()
    } else {
        toml_string(key)
    }
}

/// A TOML basic string holding `value`.
fn toml_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", u32::from(c))),
            c => out.push(c),
        }
    }
    out.push('"');

    out
}

