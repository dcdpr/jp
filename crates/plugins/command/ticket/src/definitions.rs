//! Definitions for the tools this plugin serves.
//!
//! `jp ticket tools init` writes a starting set, one file per tool, for a
//! project to load and adjust; from then on the project owns them.
//! `jp ticket tools sync` writes the one part that mirrors configuration: the
//! board's labels, offered in the schemas of the tools that take them.
//! It owns a file of its own, [`SYNCED_FILE`], and rewrites it whole, so edits
//! to the definitions survive it.

use std::{
    fs::{self, OpenOptions},
    io::{self, Write as _},
};

use camino::Utf8Path;
use serde_json::Value;
use ticket::{Unique, Vocabulary};

use crate::Output;

/// The definitions `tools init` writes, by file name.
pub(crate) const DEFINITIONS: &[(&str, &str)] = &[
    ("comment.toml", include_str!("../tools/comment.toml")),
    ("create.toml", include_str!("../tools/create.toml")),
    ("edit.toml", include_str!("../tools/edit.toml")),
    ("list.toml", include_str!("../tools/list.toml")),
    ("show.toml", include_str!("../tools/show.toml")),
];

/// The file `tools sync` writes, inside the definitions directory.
pub(crate) const SYNCED_FILE: &str = "synced.toml";

/// The line a synced file opens with.
///
/// A file in its place without it was not written by `tools sync`, and is left
/// alone.
const SYNCED_HEADER: &str = "# Generated by `jp ticket tools sync`.";

/// What a synced file says about itself, below [`SYNCED_HEADER`].
const SYNCED_NOTES: &str = "\
#
# Mirrors the board's labels into the schemas of the tools that take them, so
# the assistant is offered them rather than guessing. Run the command again
# after changing the labels or the tools: this file is rewritten whole, and
# edits to it are lost.
#
# The lists differ. `create` is offered the labels it may add. `edit` also
# gets retired ones, because replacing a ticket's whole set means naming a
# retired label to keep it. `list` also gets a bare key per facet, which is how
# a filter asks for any value under it.
#
# A key the board bounds with `min` or `max`, or makes `unique`, is described
# beside the lists of `create` and `edit`, and `create` requires labels when a
# key needs one, so the assistant knows before its first call.
#
# A board with a key that takes any value gets no lists at all: a list holds
# only the values it names, so it would refuse that key's. Its labels are
# described in words instead.
";

/// The plugin a tool's `source` has to name for the tool to be one of ours.
const PLUGIN: &str = "ticket";

/// Write the starting definitions into `dir`, creating it if needed.
///
/// Refuses before writing anything when one of the files is already there.
pub(crate) fn init(dir: &Utf8Path) -> Result<Output, String> {
    let existing: Vec<String> = DEFINITIONS
        .iter()
        .map(|(name, _)| dir.join(name))
        .filter(|path| path.exists())
        .map(|path| path.to_string())
        .collect();
    if !existing.is_empty() {
        return Err(format!(
            "Refusing to overwrite {}. Move them aside first.",
            existing.join(", ")
        ));
    }

    fs::create_dir_all(dir).map_err(|error| format!("failed to create {dir}: {error}"))?;

    let mut text = String::new();
    for (name, content) in DEFINITIONS {
        let path = dir.join(name);
        // `create_new` rather than a plain write, so a file that appeared since
        // the check above is still not overwritten.
        OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
            .and_then(|mut file| file.write_all(content.as_bytes()))
            .map_err(|error| format!("failed to write {path}: {error}"))?;
        text.push_str(&format!("Wrote {path}\n"));
    }

    text.push_str(&format!(
        "Load the directory from the workspace configuration, then run `jp ticket tools sync \
         {dir}` to offer the board's labels.\n"
    ));

    Ok(text.into())
}

/// Write the board's labels into the schemas of the configured tools that take
/// them, as `dir`'s synced file.
///
/// Tools are found by their `source` in `config`, not by their key, so a tool
/// renamed in configuration still gets its labels under the name it has there.
/// A tool whose definition leaves out the `labels` parameter gets none: the
/// synced file adds only the accepted values, and values alone would make a
/// parameter without a type, which leaves the tool out of every conversation.
pub(crate) fn sync(
    dir: &Utf8Path,
    config: &Value,
    vocabulary: &Vocabulary,
) -> Result<Output, String> {
    if !dir.is_dir() {
        return Err(format!("{dir} is not a directory."));
    }

    let path = dir.join(SYNCED_FILE);
    match fs::read_to_string(&path) {
        Ok(existing) if !existing.starts_with(SYNCED_HEADER) => {
            return Err(format!(
                "{path} was not written by `jp ticket tools sync`, so it is left alone. Move it \
                 aside first."
            ));
        }
        Ok(_) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(error) => return Err(format!("{path}: {error}")),
    }

    let (tools, undeclared): (Vec<_>, Vec<_>) = served_tools(config)
        .into_iter()
        .filter(|(_, tool)| tokens(tool, vocabulary).is_some())
        .partition(|(key, _)| declares(config, key, "labels"));

    fs::write(&path, synced(&tools, vocabulary))
        .map_err(|error| format!("failed to write {path}: {error}"))?;

    let keys: Vec<&str> = tools.iter().map(|(key, _)| key.as_str()).collect();
    let mut text = if keys.is_empty() {
        format!("Wrote {path}; no configured tool takes labels from `jp ticket`.\n")
    } else {
        format!("Wrote {path}, with labels for {}\n", keys.join(", "))
    };
    if !undeclared.is_empty() {
        let keys: Vec<&str> = undeclared.iter().map(|(key, _)| key.as_str()).collect();
        text.push_str(&format!(
            "Left out {}: their definitions declare no `labels` parameter.\n",
            keys.join(", ")
        ));
    }

    Ok(text.into())
}

/// Whether the configured tool `key` declares the parameter `name`, with a
/// type.
///
/// The values a previous sync wrote don't count: they carry no type.
fn declares(config: &Value, key: &str, name: &str) -> bool {
    config
        .get("conversation")
        .and_then(|conversation| conversation.get("tools"))
        .and_then(|tools| tools.get(key))
        .and_then(|tool| tool.get("parameters"))
        .and_then(|parameters| parameters.get(name))
        .and_then(|parameter| parameter.get("type"))
        .is_some_and(|kind| !kind.is_null())
}

/// The configured tools this plugin serves, as `(key, tool)` pairs ordered by
/// key.
///
/// `tool` is the name the plugin knows it by: the last part of its `source`, or
/// its key when the source names only the plugin.
pub(crate) fn served_tools(config: &Value) -> Vec<(String, String)> {
    let Some(tools) = config
        .pointer("/conversation/tools")
        .and_then(Value::as_object)
    else {
        return vec![];
    };

    let mut served: Vec<(String, String)> = tools
        .iter()
        .filter_map(|(key, tool)| {
            let source = tool.get("source")?.as_str()?;
            let rest = source.strip_prefix("plugin.command.")?;
            let (plugin, name) = rest.split_once('.').unwrap_or((rest, key.as_str()));

            (plugin == PLUGIN).then(|| (key.clone(), name.to_owned()))
        })
        .collect();
    served.sort();

    served
}

/// The labels a tool is offered, or `None` for a tool that takes none.
///
/// `create` gets the values it may add.
/// `edit` also gets retired ones, because replacing a ticket's whole set means
/// naming a retired value to keep it.
/// `list` also gets a bare key per facet, which is how a filter asks for any
/// value under it.
fn tokens(tool: &str, vocabulary: &Vocabulary) -> Option<Vec<String>> {
    match tool {
        "create" => Some(vocabulary.tokens()),
        "edit" => Some(vocabulary.tokens_including_retired()),
        "list" => {
            let mut tokens = vocabulary.tokens_including_retired();
            tokens.extend(vocabulary.keys().map(ToOwned::to_owned));
            tokens.sort();
            tokens.dedup();
            Some(tokens)
        }
        _ => None,
    }
}

/// Render the synced file for `tools`, each a `(key, tool)` pair that takes
/// labels.
fn synced(tools: &[(String, String)], vocabulary: &Vocabulary) -> String {
    let mut out = format!("{SYNCED_HEADER}\n{SYNCED_NOTES}");

    if vocabulary.is_empty() {
        out.push_str("#\n# The board defines no labels, so the tools take any label.\n");
        return out;
    }

    let rules = rules(vocabulary);
    let open: Vec<&str> = vocabulary.open_keys().collect();
    let required = vocabulary.facets().any(|(_, facet)| facet.min() > 0);

    for (key, tool) in tools {
        let Some(tokens) = tokens(tool, vocabulary) else {
            continue;
        };
        let key = toml_key(key);
        // A filter names no ticket's whole set, so the rules don't apply to it.
        let rules = rules.as_deref().filter(|_| tool != "list");

        if tool == "create" && required {
            out.push_str(&format!(
                "\n[conversation.tools.{key}.parameters.labels]\nrequired = true\n"
            ));
        }
        out.push_str(&format!(
            "\n[conversation.tools.{key}.parameters.labels.items]\n"
        ));
        if let Some(summary) = summary(&tokens, &open, rules) {
            out.push_str(&format!("summary = {}\n", toml_string(&summary)));
        }
        if !open.is_empty() {
            continue;
        }
        out.push_str("enum = [\n");
        for token in tokens {
            out.push_str(&format!("  {},\n", toml_string(&token)));
        }
        out.push_str("]\n");
    }

    out
}

/// The description of one label in a tool's schema, or `None` when the list of
/// accepted values says all there is.
///
/// With `open` keys there is no list, so the labels are named here instead.
fn summary(tokens: &[String], open: &[&str], rules: Option<&str>) -> Option<String> {
    if open.is_empty() && rules.is_none() {
        return None;
    }

    let mut summary = "One `key=value` label".to_owned();
    if !open.is_empty() {
        let any = open
            .iter()
            .map(|key| format!("{key}=<value>"))
            .collect::<Vec<_>>()
            .join(", ");
        summary.push_str(&if tokens.is_empty() {
            format!(": {any}, with any value")
        } else {
            format!(": {}, or {any} with any value", tokens.join(", "))
        });
    }
    summary.push('.');
    if let Some(rules) = rules {
        summary.push(' ');
        summary.push_str(rules);
    }

    Some(summary)
}

/// What the board's bounded and unique keys ask of a ticket, as sentences, or
/// `None` when no key asks anything.
fn rules(vocabulary: &Vocabulary) -> Option<String> {
    let bounds: Vec<String> = vocabulary
        .facets()
        .filter_map(|(key, facet)| facet.bound().map(|bound| format!("{bound} under `{key}`")))
        .collect();

    let mut sentences = vec![];
    if let Some((last, rest)) = bounds.split_last() {
        let all = if rest.is_empty() {
            last.clone()
        } else {
            format!("{} and {last}", rest.join(", "))
        };
        sentences.push(format!("A ticket carries {all}."));
    }
    for (key, facet) in vocabulary.facets() {
        match facet.unique() {
            Some(Unique::KeyValue) if !facet.is_bare() => {
                sentences.push(format!("Only one ticket carries each `{key}` value."));
            }
            Some(_) => sentences.push(format!("Only one ticket carries `{key}`.")),
            None => {}
        }
    }

    (!sentences.is_empty()).then(|| sentences.join(" "))
}

/// A TOML key: bare when it can be, quoted otherwise.
fn toml_key(key: &str) -> String {
    let bare = !key.is_empty()
        && key
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-');

    if bare {
        key.to_owned()
    } else {
        toml_string(key)
    }
}

/// A TOML basic string holding `value`.
fn toml_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if c.is_control() => out.push_str(&format!("\\u{:04X}", u32::from(c))),
            c => out.push(c),
        }
    }
    out.push('"');

    out
}

