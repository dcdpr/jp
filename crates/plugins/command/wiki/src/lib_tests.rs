#[test]
fn archiving_refuses_a_page_with_active_children() {
    let root = workspace();
    run_args(root.path(), &["add", "Parent", "--summary", "P."]);
    let parent = id_of(&page_file(root.path(), "parent"));
    run_args(root.path(), &[
        "add",
        "Child",
        "--summary",
        "C.",
        "--parent",
        &parent,
    ]);
    let child = id_of(&page_file(root.path(), "child"));

    let (_, _, code, reason) = run_args(root.path(), &["archive", &parent]);
    assert_eq!(code, 1);
    assert_eq!(
        reason.unwrap(),
        format!(
            "{parent} has active children: {child}. Archive them, or give them another parent, \
             first."
        )
    );

    let (text, _, code, _) = run_args(root.path(), &[
        "archive",
        &child,
        "--superseded-by",
        &parent,
    ]);
    assert_eq!(code, 0);
    assert!(text.ends_with(": Reference -> Archived\n"), "{text}");
    let source = fs::read_to_string(page_file(root.path(), "child")).unwrap();
    assert!(source.contains("- **Status**: Archived\n"), "{source}");
    assert!(
        source.contains(&format!("- **Superseded by**: {parent}\n- **Summary**: C.")),
        "{source}"
    );

    let (listed, _, _, _) = run_args(root.path(), &["list"]);
    assert!(!listed.contains(&child), "{listed}");
    let (listed, _, _, _) = run_args(root.path(), &["list", "--archived"]);
    assert!(listed.starts_with(&child), "{listed}");
}

#[test]
fn a_ticket_moves_into_the_wiki_once() {
    let root = workspace();

    let (text, chrome, code, reason) = run_args(root.path(), &[
        "from-ticket",
        "T-02wt0kx",
        "--status",
        "snapshot",
        "--summary",
        "What the paper found.",
    ]);
    assert_eq!((code, reason), (0, None));
    let file = page_file(root.path(), "paper-notes");
    let id = id_of(&file);
    assert!(
        text.contains("docs/ticket/02wt0kx-paper-notes.md: promoted to"),
        "{text}"
    );
    assert!(
        chrome.contains("Left out the labels the wiki doesn't take: type=note."),
        "{chrome}"
    );

    let source = fs::read_to_string(&file).unwrap();
    assert!(source.contains("- **Status**: Snapshot\n"), "{source}");
    assert!(
        source.contains("- **Authors**: Jane Doe\n- **Date**: 2026-08-05\n"),
        "{source}"
    );
    assert!(source.contains("- **Label**: domain=llm\n"), "{source}");
    assert!(
        source.ends_with("What the paper found.\n\nMoved from ticket T-02wt0kx.\n"),
        "{source}"
    );

    let ticket =
        fs::read_to_string(root.path().join("docs/ticket/02wt0kx-paper-notes.md")).unwrap();
    assert!(
        ticket.contains(&format!("- **Promoted to**: {id}\n")),
        "{ticket}"
    );
    assert!(ticket.contains("- **Status**: Done\n"), "{ticket}");

    let (again, _, code, _) = run_args(root.path(), &["from-ticket", "T-02wt0kx"]);
    assert_eq!(code, 0);
    assert!(
        again.starts_with(&format!("T-02wt0kx is already moved to {id}")),
        "{again}"
    );
}

