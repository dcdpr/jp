/// A tool call is answered with its outcome, then a clean exit, whatever the
/// outcome says: a refusal is the assistant's to read, not a failed run.
#[test]
fn a_tool_call_is_answered_with_its_outcome() {
    let root = workspace();
    run_args(root.path(), &["add", "Runbook", "--summary", "R."]);
    let id = id_of(&page_file(root.path(), "runbook"));

    let message = match init_message(root.path(), &[], OutputFormat::default()) {
        HostToPlugin::Init(mut init) => {
            init.tool = Some(ToolCall {
                action: ToolAction::Run,
                name: "list".to_owned(),
                arguments: Map::new(),
                answers: Map::new(),
                options: Map::new(),
                access: None,
                conversation: "test".to_owned(),
            });
            HostToPlugin::Init(init)
        }
        other => other,
    };
    let input = serde_json::to_string(&message).unwrap() + "\n";
    let mut output = vec![];
    run(input.as_bytes(), &mut output).unwrap();

    let mut outcome = None;
    let mut code = None;
    for line in String::from_utf8(output).unwrap().lines() {
        match serde_json::from_str::<PluginToHost>(line).unwrap() {
            PluginToHost::ToolOutcome(message) => {
                outcome = Some(serde_json::from_value::<Outcome>(message.outcome).unwrap());
            }
            PluginToHost::Exit(exit) => code = Some(exit.code),
            _ => {}
        }
    }

    assert_eq!(code, Some(0));
    assert_eq!(
        outcome,
        Some(Outcome::Success {
            content: format!("{id}  Reference  Runbook\n")
        })
    );
}

