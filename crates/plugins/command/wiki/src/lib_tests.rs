/// A workspace with an initialized wiki and one ticket.
fn workspace() -> Utf8TempDir {
    let root = Utf8TempDir::new().unwrap();
    let wiki = root.path().join("docs/wiki");
    let tickets = root.path().join("docs/ticket");
    fs::create_dir_all(&wiki).unwrap();
    fs::create_dir_all(&tickets).unwrap();
    fs::write(wiki.join(".epoch"), "2026-08-10\n").unwrap();
    fs::write(tickets.join(".epoch"), "2026-08-10\n").unwrap();
    fs::write(
        tickets.join("02wt0kx-paper-notes.md"),
        concat!(
            "# Paper notes\n\n",
            "- **Status**: Todo\n",
            "- **Authors**: Jane Doe\n",
            "- **Date**: 2026-08-05\n",
            "- **Label**: type=note\n",
            "- **Label**: domain=llm\n\n",
            "What the paper found.\n",
        ),
    )
    .unwrap();

    root
}

fn init_message(root: &Utf8Path, args: &[&str], format: OutputFormat) -> HostToPlugin {
    HostToPlugin::Init(Box::new(InitMessage {
        version: jp_plugin::PROTOCOL_VERSION,
        workspace: WorkspaceInfo {
            root: root.to_path_buf(),
            storage: root.join(".jp"),
            id: "test".to_owned(),
        },
        paths: PathsInfo::default(),
        config: json!({ "user": { "name": "Jane Doe <jane@example.com>" } }),
        options: Map::from_iter([(
            "labels".to_owned(),
            json!({ "domain": { "description": "The subsystem", "values": ["llm", "storage"] } }),
        )]),
        args: args.iter().map(|arg| (*arg).to_owned()).collect(),
        log_level: 0,
        output_format: format,
        tool: None,
    }))
}

/// Run `args` the way the host does, returning what was printed on stdout and
/// on stderr, and the exit code with its reason.
fn run_args(root: &Utf8Path, args: &[&str]) -> (String, String, u8, Option<String>) {
    run_as(root, args, OutputFormat::default())
}

fn run_as(
    root: &Utf8Path,
    args: &[&str],
    format: OutputFormat,
) -> (String, String, u8, Option<String>) {
    let input = serde_json::to_string(&init_message(root, args, format)).unwrap() + "\n";
    let mut output = vec![];
    run(input.as_bytes(), &mut output).unwrap();

    let mut text = String::new();
    let mut chrome = String::new();
    let mut exit = None;
    for line in String::from_utf8(output).unwrap().lines() {
        match serde_json::from_str::<PluginToHost>(line).unwrap() {
            PluginToHost::Print(print) if print.channel == "content" => text.push_str(&print.text),
            PluginToHost::Print(print) => chrome.push_str(&print.text),
            PluginToHost::Exit(done) => exit = Some((done.code, done.reason)),
            _ => {}
        }
    }
    let (code, reason) = exit.expect("the plugin exits");

    (text, chrome, code, reason)
}

/// The one page file in the wiki directory whose name ends with `slug.md`.
fn page_file(root: &Utf8Path, slug: &str) -> Utf8PathBuf {
    let dir = root.join("docs/wiki");
    let found: Vec<Utf8PathBuf> = fs::read_dir(&dir)
        .unwrap()
        .map(|entry| Utf8PathBuf::try_from(entry.unwrap().path()).unwrap())
        .filter(|path| path.as_str().ends_with(&format!("-{slug}.md")))
        .collect();
    assert_eq!(found.len(), 1, "{found:?}");

    found[0].clone()
}

/// The id of the page in `file`, from its name.
fn id_of(file: &Utf8Path) -> String {
    format!("W-{}", &file.file_name().unwrap()[..7])
}

