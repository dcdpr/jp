#[test]
fn a_page_is_added_shown_listed_and_checked() {
    let root = workspace();

    let (text, chrome, code, reason) = run_args(root.path(), &[
        "add",
        "Ubiquitous",
        "Language",
        "--summary",
        "The words the project uses.",
        "--label",
        "domain=llm",
        "--body",
        "## Turn\n\nOne cycle.",
    ]);
    assert_eq!((code, reason), (0, None));
    assert_eq!(chrome, "");
    let file = page_file(root.path(), "ubiquitous-language");
    let id = id_of(&file);
    assert_eq!(
        text,
        format!("Created docs/wiki/{} ({id})\n", file.file_name().unwrap())
    );

    let source = fs::read_to_string(&file).unwrap();
    assert_eq!(
        source,
        "# Ubiquitous Language\n\n- **Status**: Reference\n- **Authors**: Jane Doe \
         <jane@example.com>\n- **Date**: "
            .to_owned()
            + &crate::cmd::today()
            + "\n- **Label**: domain=llm\n- **Summary**: The words the project uses.\n\n## \
               Turn\n\nOne cycle.\n"
    );

    let (shown, _, code, _) = run_args(root.path(), &["show", &id]);
    assert_eq!(code, 0);
    assert!(
        shown.starts_with(&format!("# {id}: Ubiquitous Language\n")),
        "{shown}"
    );
    assert!(
        shown.ends_with("## Contents\n\n- Turn `#turn`\n"),
        "{shown}"
    );

    let (listed, _, _, _) = run_args(root.path(), &["list"]);
    assert_eq!(
        listed,
        format!("{id}  Reference  Ubiquitous Language [domain=llm]\n")
    );

    // A lone page is an orphan, which warns without failing.
    let (checked, _, code, _) = run_args(root.path(), &["check"]);
    assert_eq!(code, 0, "{checked}");
    assert!(checked.contains("is an orphan"), "{checked}");
    assert!(
        checked.ends_with("Checked 1 page: 0 errors, 1 warning.\n"),
        "{checked}"
    );

    let (_, _, code, _) = run_args(root.path(), &["check", "--strict"]);
    assert_eq!(code, 1);
}

