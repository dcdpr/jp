#!/usr/bin/env bash
#
# Release JP's history after the fact, in periods of about six weeks, with the
# commands any release uses, in a clone where nothing reaches GitHub until the
# trial ends (RFD 123, "JP's history"). `just backfill` runs it:
#
#   init [DIR]     From a checkout of the branch to release from, which has to
#                  hold GitHub's `main`: make DIR, `jp-backfill` beside the
#                  checkout by default, holding `origin.git`, a bare repository
#                  standing in for GitHub, and `jp`, a clone of it whose `main`
#                  merges the branch.
#   next           In the clone: draft the next period's fragments, cut its
#                  release at the day you choose, build it for this Mac, and
#                  check out its notes branch.
#   proceed        File the notes, finalize and build the release, then start
#                  the next period.
#   revert VER     Take back release VER and every later one, so VER can be cut
#                  again.
#   publish        End the trial: publish every release to GitHub.
#   draft COMMIT   Draft fragments for the changes after COMMIT on HEAD's
#                  first-parent line that have none, for you to review.
#
# The history runs to GitHub's `main` as `init` found it. The branch's own
# fragments, and whatever reaches GitHub's `main` during the trial, ship in the
# first release cut after the trial's pull request merges.
#
# The clone is a JP workspace of its own, with a workspace ID only it knows, so
# its conversations and builds stay apart from the checkout's. `jp`, `jp
# release`, `jp release github`, and `comfort` are built from the checkout
# `init` ran in, as this script is run from it, so a fix made there takes effect
# at the next command; `next` and `proceed` also merge the branch's newer
# commits into the clone's `main`.
#
# Drafting runs `jp query` with the `prose` persona and the instructions in
# backfill.md, beside this script, and reads its answer as JSON.
#
# Runs on the bash macOS ships, 3.2, and needs git, jq, and cargo.

set -euo pipefail

# The directory releases keep their notes in.
FRAGMENTS=changelog.d

# The commit the test tag `v0.1.0` named, where the first period ends unless
# you choose another day.
FIRST_END=3e59e1b76e5297ab86ab29d9f292be6672096a64

# How many days after the previous period's last day `next` suggests.
PERIOD=42

# The branch on GitHub whose pull request brings the history's notes into
# `main`.
HISTORY_BRANCH=release-history

# The first line of `.jp/.id`, as JP writes it.
ID_PREAMBLE='DO NOT EDIT THIS FILE! IT IS AUTO-GENERATED BY JP.'

# The fragment types, as RFD 121 defines them.
TYPES='["added","changed","deprecated","removed","fixed","security","performance"]'

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

say() { printf '%s\n' "$*"; }
die() {
  printf 'backfill: %s\n' "$*" >&2
  exit 1
}

usage() {
  sed -n '3,22s/^# \{0,1\}//p' "${BASH_SOURCE[0]}"
  exit 2
}

short() { git rev-parse --short=7 "$1"; }

# The lines of $1 joined with spaces.
joined() { printf '%s\n' "$1" | paste -s -d ' ' -; }

# A setting `init` recorded in the clone's git configuration; empty outside it.
setting() { git config --get "jp-backfill.$1" || true; }

in_clone() { [ -n "$(setting history)" ]; }

need_clone() {
  in_clone || die "Run \`just backfill $1\` in the clone \`just backfill init\` made."
}

# Build `jp` and `comfort` from the checkout the trial runs from, or this one
# outside a trial, and install its `jp-release`, and its `jp-release-github`
# when $1 is `github`. Sets JP and COMFORT to the binaries.
tools() {
  local source target
  source=$(setting source)
  [ -n "$source" ] || source=$(pwd)
  [ -f "$source/Cargo.toml" ] || die "The checkout the trial runs from, $source, is gone."

  say "Building jp from $source."
  cargo build --locked --quiet --manifest-path "$source/Cargo.toml" \
    --package jp_cli --package comfort
  target=$(cargo metadata --format-version 1 --no-deps --manifest-path "$source/Cargo.toml" |
    jq -r .target_directory)
  JP=$target/debug/jp
  COMFORT=$target/debug/comfort

  cargo install --locked --quiet --debug --path "$source/crates/plugins/command/release"
  if [ "${1:-}" = github ]; then
    cargo install --locked --quiet --debug --path "$source/crates/plugins/command/release-github"
  fi
}

jp() { "$JP" "$@"; }

# Run jp with git's dates set to noon UTC of the day $1, so the commits and tags
# it makes are dated that day.
dated_jp() {
  local at
  at="$(noon "$1") +0000"
  shift
  env GIT_AUTHOR_DATE="$at" GIT_COMMITTER_DATE="$at" "$JP" "$@"
}

# The Unix time of noon UTC on the day $1, `YYYY-MM-DD`.
noon() {
  date -u -j -f '%Y-%m-%d %H:%M:%S' "$1 12:00:00" +%s 2>/dev/null ||
    date -u -d "$1 12:00:00" +%s
}

# The day $2 days after the day $1.
day_after() {
  date -u -j -v+"$2"d -f %Y-%m-%d "$1" +%Y-%m-%d 2>/dev/null ||
    date -u -d "$1 + $2 days" +%Y-%m-%d
}

# Whether $1 is a day of the calendar, written `YYYY-MM-DD`.
is_day() {
  [[ $1 =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || return 1
  local normal
  normal=$(date -u -j -f %Y-%m-%d "$1" +%Y-%m-%d 2>/dev/null ||
    date -u -d "$1" +%Y-%m-%d 2>/dev/null) || return 1
  [ "$normal" = "$1" ]
}

# The finalized releases' versions, oldest first.
tagged() { git tag --list 'v[0-9]*' --sort=v:refname | sed 's/^v//'; }

# The newest finalized release's version; empty before the first.
latest() { tagged | sed -n '$p'; }

# Versions read from standard input, newest first.
newest_first() { sort -t. -k1,1nr -k2,2nr -k3,3nr; }

# Whether version $1 is $2 or later.
at_least() { [ "$(printf '%s\n%s\n' "$1" "$2" | newest_first | sed -n 1p)" = "$1" ]; }

# The releases in preparation: started on a release branch, without a tag.
preparing() {
  local branch version
  for branch in $(git for-each-ref --format='%(refname:short)' refs/heads/release); do
    for version in $(git log --format='%(trailers:key=Starts-Release,valueonly)' "main..$branch"); do
      if ! git rev-parse --quiet --verify "refs/tags/v$version" >/dev/null; then
        printf '%s\n' "$version"
      fi
    done
  done
}

# The commit that starts release $1 on its release branch.
start_of() {
  git log -1 --format=%H --fixed-strings --grep="Starts-Release: $1" "refs/heads/release/${1%.*}"
}

# The version the next period's release takes: the minor release after the
# newest, or 0.1.0 for the first.
next_version() {
  local latest minor
  latest=$(latest)
  if [ -z "$latest" ]; then
    echo 0.1.0
    return
  fi
  minor=${latest#*.}
  minor=${minor%%.*}
  echo "${latest%%.*}.$((minor + 1)).0"
}

count_of() { printf '%s\n' "$1" | grep -c . || true; }

# JP's per-user data directory, as JP finds it.
data_dir() {
  if [ -n "${JP_USER_DATA_DIR:-}" ]; then
    printf '%s\n' "$JP_USER_DATA_DIR"
  elif [[ ${XDG_DATA_HOME:-} == /* ]]; then
    printf '%s\n' "$XDG_DATA_HOME/jp"
  elif [ "$(uname -s)" = Darwin ]; then
    printf '%s\n' "$HOME/Library/Application Support/jp"
  else
    printf '%s\n' "$HOME/.local/share/jp"
  fi
}

workspace_id() { awk 'NF { id = $0 } END { print id }' .jp/.id; }

# A workspace ID, five characters JP accepts.
new_id() {
  local chars=0123456789abcdefghijklmnopqrstuvwxyz id='' _
  for _ in 1 2 3 4 5; do
    id="$id${chars:RANDOM%36:1}"
  done
  printf '%s\n' "$id"
}

# Where `jp release build` keeps this workspace's builds; empty until JP has
# made the workspace's storage.
builds() {
  local dir id
  id=$(workspace_id)
  # JP names the directory `<slug>-<id>`, or `<id>` for a root without a name.
  for dir in "$(data_dir)/workspace/"*-"$id" "$(data_dir)/workspace/$id"; do
    if [ -d "$dir" ]; then
      printf '%s\n' "$dir/release"
      return
    fi
  done
}

# Whether a publishable build of release $1 is kept: one made with the release
# profile from the commit its tag names.
publishable() {
  local manifest
  manifest="$(builds)/$1/manifest.json"
  [ -f "$manifest" ] || return 1
  [ "$(jq -r '.profile + " " + .commit' "$manifest")" = "release $(git rev-parse "v$1^{commit}")" ]
}

# Delete the kept build of release $1, if there is one.
remove_build() {
  local builds
  builds=$(builds)
  if [ -n "$builds" ] && [ -d "$builds/$1" ]; then
    rm -rf -- "${builds:?}/$1"
  fi
}

push_main() { git push --quiet origin main; }

# Make the stand-in's release branches, notes branches, and tags match this
# repository's.
mirror() {
  git push --quiet --prune --force origin \
    'refs/heads/release/*:refs/heads/release/*' \
    'refs/heads/release-notes/*:refs/heads/release-notes/*' \
    'refs/tags/v*:refs/tags/v*'
}

# Check out `main`, refusing to leave changes behind on another branch.
on_main() {
  local branch
  branch=$(git symbolic-ref --quiet --short HEAD || true)
  [ "$branch" != main ] || return 0
  [ -z "$(git status --porcelain)" ] ||
    die "Commit or discard the changes on ${branch:-the detached HEAD} first."
  git checkout --quiet main
}

clean_outside_fragments() {
  [ -z "$(git status --porcelain -- . ":(exclude)$FRAGMENTS")" ] ||
    die "Commit or discard the changes outside $FRAGMENTS/ first."
}

# Merge the commits the branch the trial runs from has gained into `main`.
refresh() {
  local branch
  branch=$(setting branch)
  git fetch --quiet --no-tags "$(setting git)" "+refs/heads/$branch:refs/backfill/source"
  if git merge-base --is-ancestor refs/backfill/source main; then
    return
  fi

  say "Merging the newer commits of $branch into main."
  if ! git merge --quiet --no-ff --no-edit \
    -m "chore: Merge \`$branch\` into the history to release" refs/backfill/source; then
    git merge --abort
    die "Merging $branch into main conflicts; merge it by hand with \`git merge refs/backfill/source\`, commit, and run this again."
  fi
  push_main
}

# Lay out the fragments directory as CI checks it, and check it.
tidy() {
  local said
  "$COMFORT" --language markdown "$FRAGMENTS"
  if ! said=$(jp release check 2>&1); then
    printf '%s\n' "$said" >&2
    die "Fix the fragments \`jp release check\` names, then run this again."
  fi
}

# The changes the fragments describe already, one per line: each `Credits`
# value, and for a fragment at the top level without any, the commit that added
# it.
noted() {
  local file credits
  find "$FRAGMENTS" -type f -name '*.md' ! -path '*/highlights/*' \
    ! -name README.md ! -name overview.md |
    while IFS= read -r file; do
      credits=$(sed -n 's/^- \*\*[Cc][Rr][Ee][Dd][Ii][Tt][Ss]\*\*: *//p' "$file")
      if [ -n "$credits" ]; then
        printf '%s\n' "$credits"
      elif [ "$(dirname "$file")" = "$FRAGMENTS" ]; then
        git log --first-parent --diff-filter=A --format=%H -1 -- "$file" || true
      fi
    done
}

# List the changes in the range $1 on HEAD's first-parent line that none of the
# credits in the file $3 notes, as Markdown, and write their credits to the
# file $2, one per line: `#<number>` for a pull request, or the first 12
# characters of the commit's hash.
changes() {
  git log --first-parent --reverse --format='%H%x1f%cs%x1f%s%x1f%b%x1e' "$1" |
    awk -v FS='\037' -v credits="$2" -v noted="$3" '
      BEGIN {
        # The noted file has a credit per line; the log has a change per record,
        # ended by \036. RS applies to getline too, so it changes after reading.
        while ((getline line < noted) > 0) {
          gsub(/^[ \t]+|[ \t]+$/, "", line)
          if (line ~ /^#[0-9]+$/) seen[line] = 1
          else if (line != "") hashes[++known] = tolower(line)
        }
        close(noted)
        RS = "\036"
      }
      {
        sub(/^\n+/, "")
        if ($0 == "") next
        hash = $1; day = $2; subject = $3; body = $4
        if (match(subject, /\(#[0-9]+\)$/))
          credit = "#" substr(subject, RSTART + 2, RLENGTH - 3)
        else if (match(subject, /^Merge pull request #[0-9]+/))
          credit = "#" substr(subject, RSTART + 20, RLENGTH - 20)
        else
          credit = substr(hash, 1, 12)
        if (credit in seen) next
        for (i = 1; i <= known; i++) if (index(hash, hashes[i]) == 1) next

        print credit > credits
        printf "### %s (%s) %s\n\n", credit, day, subject
        count = split(body, text, "\n")
        while (count > 0 && text[count] ~ /^[ \t\r]*$/) count--
        shown = count < 20 ? count : 20
        for (i = 1; i <= shown; i++) print "> " text[i]
        if (count > shown) print "> (" count - shown " more lines)"
        if (count > 0) print ""
      }'
}

# The JSON schema of a drafting answer.
schema() {
  cat <<'JSON'
{
  "type": "object",
  "properties": {
    "fragments": {
      "type": "array",
      "description": "One fragment per user-visible change; empty when no change is user-visible.",
      "items": {
        "type": "object",
        "properties": {
          "type": {
            "type": "string",
            "enum": ["added", "changed", "deprecated", "removed", "fixed", "security", "performance"],
            "description": "What the change means for users."
          },
          "slug": {
            "type": "string",
            "description": "Two to five lowercase words joined by hyphens that name the change."
          },
          "credits": {
            "type": "array",
            "items": { "type": "string" },
            "description": "The credit of each listed change the fragment describes, copied from its heading."
          },
          "entry": {
            "type": "string",
            "description": "One or two sentences for someone using JP, in Markdown."
          },
          "upgrade_title": {
            "type": "string",
            "description": "For a change that requires users to act, what broke; empty otherwise."
          },
          "upgrade_body": {
            "type": "string",
            "description": "For a change that requires users to act, what to do instead, in Markdown; empty otherwise."
          }
        },
        "required": ["type", "slug", "credits", "entry", "upgrade_title", "upgrade_body"],
        "additionalProperties": false
      }
    }
  },
  "required": ["fragments"],
  "additionalProperties": false
}
JSON
}

# Pick the answer out of `jp --format json query`'s output, one conversation
# event per line: the `data` of the last chat response that holds a list of
# fragments. The request's event carries the schema, which names `fragments`
# too, so only a response's `data` counts.
# shellcheck disable=SC2016 # jq's syntax, not the shell's.
ANSWER_JQ='
  fromjson? | objects | select(.type == "chat_response")
  | .data | objects | select(.fragments | type == "array")
'

# Turn each fragment of a drafting answer into `{slug, type, content}`, the
# file's text, or `{dropped}`, why it can't be written: an unknown type, no
# entry, or no credit among `$credits`, the period's, one per line.
# Credits are normalized to `#<number>` and to the listed form of a hash.
# shellcheck disable=SC2016 # jq's variables, not the shell's.
FRAGMENTS_JQ='
  def trimmed: tostring | gsub("^\\s+|\\s+$"; "");
  ($credits | split("\n") | map(trimmed) | map(select(length > 0))) as $allowed
  | def credit:
      trimmed as $c
      | if ($c | test("^#?[0-9]+$")) then "#" + ($c | ltrimstr("#"))
        elif ($c | test("^[0-9a-fA-F]{7,40}$")) then
          ($c | ascii_downcase) as $h
          | (([$allowed[] | select(startswith("#") | not)
               | select(startswith($h) or ($h | startswith(.)))] | first) // $h)
        else $c end;
    .fragments[]? as $f
    | ([$f.credits[]? | credit] | unique) as $named
    | [$named[] | select(IN($allowed[]))] as $valid
    | ($f.entry // "" | trimmed) as $entry
    | ($f.type // "" | trimmed | ascii_downcase) as $type
    | ($f.slug // "" | trimmed | ascii_downcase | gsub("[^a-z0-9]+"; "-") | gsub("^-+|-+$"; "")) as $slug
    | (if $slug == "" then "change" else $slug end) as $slug
    | ($f.upgrade_title // "" | trimmed | gsub("\\s+"; " ")) as $title
    | ($f.upgrade_body // "" | trimmed) as $body
    | if ($type | IN($types[]) | not) then {dropped: "`\($slug)`, whose type `\($type)` is no fragment type"}
      elif $entry == "" then {dropped: "`\($slug)`, which has no entry"}
      elif ($valid | length) == 0 then {dropped: "`\($slug)`, which credits none of the changes listed"}
      else {
        slug: $slug,
        type: $type,
        content: (
          ($valid | map("- **Credits**: " + .) | join("\n")) + "\n\n" + $entry + "\n"
          + (if $title != "" and $body != "" then "\nBREAKING CHANGE: " + $title + "\n\n" + $body + "\n" else "" end)
        )
      }
      end
'

# Draft fragments for the changes in the range $1 that have none, for release
# $2, or the next release when $2 is empty, as changes made between the days $3
# and $4, and write them to the top of the fragments directory.
draft() {
  local range=$1 version=${2:-the next release} from=$3 until=$4
  local work count record slug type path n written=0
  work=$(mktemp -d)

  noted >"$work/noted"
  : >"$work/credits"
  changes "$range" "$work/credits" "$work/noted" >"$work/changes.md"
  count=$(grep -c . "$work/credits" || true)
  if [ "$count" -eq 0 ]; then
    say "Every change of $version has a fragment already."
    rm -rf "$work"
    return
  fi

  schema >"$work/schema.json"
  {
    sed -e "s/{version}/$version/g" -e "s/{from}/$from/g" -e "s/{until}/$until/g" \
      "$HERE/backfill.md"
    printf '\n## The changes, oldest first\n\n'
    cat "$work/changes.md"
  } >"$work/prompt.md"

  say "Drafting fragments for $count changes with the prose persona; this takes a few minutes."
  if ! jp --format json --no-interactive --cfg prose \
    query --new --local --no-edit --no-tool-use \
    --title "Draft the notes of $version" \
    --schema "@$work/schema.json" "@$work/prompt.md" \
    >"$work/answer.ndjson" 2>"$work/log"; then
    tail -n 20 "$work/log" >&2
    die "Drafting failed; its prompt and log are in $work."
  fi

  jq -R -c "$ANSWER_JQ" "$work/answer.ndjson" | sed -n '$p' >"$work/answer.json"
  [ -s "$work/answer.json" ] || die "The drafting answer holds no fragments; see $work."

  jq -c --rawfile credits "$work/credits" --argjson types "$TYPES" "$FRAGMENTS_JQ" \
    "$work/answer.json" >"$work/records"
  while IFS= read -r record; do
    if [ "$(jq -r 'has("dropped")' <<<"$record")" = true ]; then
      say "Left out $(jq -r .dropped <<<"$record")."
      continue
    fi
    slug=$(jq -r .slug <<<"$record")
    type=$(jq -r .type <<<"$record")
    path=$FRAGMENTS/$slug.$type.md
    n=1
    while [ -e "$path" ]; do
      n=$((n + 1))
      path=$FRAGMENTS/$slug-$n.$type.md
    done
    jq -j .content <<<"$record" >"$path"
    written=$((written + 1))
  done <"$work/records"

  say "Drafted $written fragments for $version."
  rm -rf "$work"
}

cmd_init() {
  local dir=${1:-} root branch github main day common standin clone id
  if in_clone; then
    die "This is the trial's clone; run \`just backfill init\` in the checkout to release from."
  fi

  root=$(pwd)
  branch=$(git symbolic-ref --quiet --short HEAD) ||
    die "HEAD is detached; check out the branch to release from."
  github=$(git remote get-url origin 2>/dev/null) ||
    die "This checkout has no \`origin\` remote to read GitHub's main from."

  say "Fetching GitHub's main."
  git fetch --quiet --no-tags origin main
  main=$(git rev-parse --verify refs/remotes/origin/main)
  day=$(git show -s --format=%cs "$main")
  git merge-base --is-ancestor "$main" HEAD ||
    die "$branch lacks commits of GitHub's main; merge them in first, with \`git merge origin/main\`."

  [ -n "$dir" ] || dir=$(dirname "$root")/jp-backfill
  [ ! -e "$dir" ] || die "$dir exists already; delete it, or name another directory with \`just backfill init <dir>\`."
  common=$(cd "$(git rev-parse --git-common-dir)" && pwd)
  id=$(new_id)
  while [ "$id" = "$(workspace_id)" ]; do id=$(new_id); done

  mkdir -p "$dir"
  dir=$(cd "$dir" && pwd)
  standin=$dir/origin.git
  clone=$dir/jp
  say "Making the trial in $dir."
  git init --quiet --bare --initial-branch=main "$standin"
  git push --quiet "$standin" "$main:refs/heads/main"
  git clone --quiet "$standin" "$clone"
  (
    cd "$clone"
    git fetch --quiet --no-tags "$common" "+refs/heads/$branch:refs/backfill/source"
    git merge --quiet --no-ff --no-edit \
      -m "chore: Merge \`$branch\` into the history to release" refs/backfill/source
    printf '%s\n%s\n' "$ID_PREAMBLE" "$id" >.jp/.id
    git update-index --skip-worktree .jp/.id
    git config jp-backfill.source "$root"
    git config jp-backfill.git "$common"
    git config jp-backfill.branch "$branch"
    git config jp-backfill.history "$main"
    git config jp-backfill.github "$github"
    git push --quiet origin main
  )

  cat <<EOF

Made the trial in $dir:

  origin.git  stands in for GitHub, with GitHub's main as of $(short "$main") ($day)
  jp          a clone of it, whose main merges $branch

The history to release runs to $(short "$main"). Release it a period at a time,
in the clone:

  cd $clone
  just backfill next

The clone is a JP workspace of its own, so its conversations and builds stay
apart from this checkout's. To back out at any time, delete the trial and the
clone's JP data:

  rm -rf "$dir" "$(data_dir)/workspace/jp-$id"
EOF
}

cmd_next() {
  need_clone next
  local preparing history history_day latest start prev_end='' prev_day='' version suggested
  local day end range eof='' count from
  preparing=$(preparing)
  [ -z "$preparing" ] ||
    die "$preparing is in preparation: finish it with \`just backfill proceed\`, or take it back with \`just backfill revert $preparing\`."
  on_main
  clean_outside_fragments
  tools
  refresh

  history=$(setting history)
  history_day=$(git show -s --format=%cs "$history")
  latest=$(latest)
  version=$(next_version)
  if [ -n "$latest" ]; then
    start=$(start_of "$latest")
    prev_end=$(git rev-parse "$start^")
    prev_day=$(git show -s --format=%cs "$start")
    [ "$prev_end" != "$history" ] ||
      die "The history is released up to $(short "$history"), GitHub's main as \`init\` found it; end the trial with \`just backfill publish\`."
    suggested=$(day_after "$prev_day" "$PERIOD")
    say "$version releases the changes after $prev_day, where $latest ends."
  else
    if git cat-file -e "$FIRST_END^{commit}" 2>/dev/null; then
      suggested=$(git show -s --format=%cs "$FIRST_END")
    else
      suggested=$(day_after "$(git log --max-parents=0 --format=%cs "$history" | sed -n 1p)" "$PERIOD")
    fi
    say "$version releases the start of JP's history."
  fi
  if [[ $suggested > $history_day ]]; then
    suggested=$history_day
  fi
  say "Suggested last day: $suggested"

  while :; do
    printf 'Last day of %s, or Enter for %s: ' "$version" "$suggested"
    if ! IFS= read -r day; then
      eof=1
      day=
      printf '\n'
    fi
    day=${day:-$suggested}
    if ! is_day "$day"; then
      say "$day isn't a day written YYYY-MM-DD."
    elif [ -n "$prev_day" ] && [[ ! $day > $prev_day ]]; then
      say "$version has to end after $prev_day, where $latest ends."
    else
      if [[ $day > $history_day ]]; then
        say "The history ends on $history_day, so $version ends there."
        day=$history_day
      fi
      end=$(git rev-list --first-parent -n 1 --before="$day 23:59:59" "$history")
      if [ -z "$end" ]; then
        say "No commit reached main by $day."
      elif [ -n "$prev_end" ] && git merge-base --is-ancestor "$end" "$prev_end"; then
        say "No change reached main between $prev_day and $day; name a later day."
      else
        break
      fi
    fi
    [ -z "$eof" ] || die "No day to end $version on."
  done

  range=$end
  [ -z "$prev_end" ] || range=$prev_end..$end
  count=$(git rev-list --first-parent --count "$range")
  say "$version ends at $(short "$end"), $(git show -s --format='%cs: %s' "$end"), with $count changes."

  from=$prev_day
  [ -n "$from" ] || from="the start of JP's history"
  draft "$range" "$version" "$from" "$day"
  tidy
  git add -- "$FRAGMENTS"
  if ! git diff --cached --quiet; then
    git commit --quiet -m "docs(changelog): Draft the notes of $version"
    push_main
  fi

  say "Cutting $version at $(short "$end"), dated $day."
  dated_jp "$day" release cut --at "$end" --version "$version" >/dev/null ||
    die "The cut failed for the reason above. The drafted fragments are on main, and \`just backfill next\` drafts only the changes still without one, so it can end $version on a later day when the period has nothing to release."
  mirror

  say "Building $version for this Mac, to check that it builds."
  if ! env JP_RELEASE_TARGETS=host "$JP" release build "$version" --quick >/dev/null; then
    die "$version doesn't build at $(short "$end"). Take it back with \`just backfill revert $version\` and end it on another day, or fix the build and run \`jp release build $version --quick\`."
  fi

  git checkout --quiet "release-notes/v$version"
  cat <<EOF

$version is cut at $(short "$end"), dated $day, and builds on this Mac. Its notes
are on release-notes/v$version, which is checked out:

  - refine them in $FRAGMENTS/$version/, where highlights and an overview.md go too
  - read them with \`jp release render $version\`, or as a draft page under
    \`just develop-docs\`
  - then run \`just backfill proceed\`, which finalizes $version, builds it, and
    starts the next period

\`just backfill revert $version\` takes it back, to end it on another day.
EOF
}

# File the notes of release $1, which is in preparation, and finalize it.
finish() {
  local version=$1 notes=release-notes/v$1 branch day
  branch=$(git symbolic-ref --quiet --short HEAD || true)
  if [ "$branch" = "$notes" ]; then
    clean_outside_fragments
    tidy
    git add -- "$FRAGMENTS"
    git diff --cached --quiet || git commit --quiet -m "docs(changelog): Edit the notes of $version"
  fi
  on_main
  refresh

  if git rev-parse --quiet --verify "refs/heads/$notes" >/dev/null &&
    ! git merge-base --is-ancestor "$notes" main; then
    if ! git merge --quiet --no-ff --no-edit -m "docs(changelog): File the notes of $version" "$notes"; then
      git merge --abort
      die "Merging $notes into main conflicts; merge it by hand, commit, and run \`just backfill proceed\` again."
    fi
  fi
  push_main
  # The stand-in's notes branch has to match this one, which finalize compares
  # with `main`.
  mirror

  day=$(git show -s --format=%cs "$(start_of "$version")")
  say "Finalizing $version, dated $day."
  dated_jp "$day" release finalize "$version" >/dev/null ||
    die "Finalizing $version failed; fix what it names, then run \`just backfill proceed\` again."
  git branch --quiet -D "$notes" 2>/dev/null || true
  mirror
}

# Build the newest release as it ships, unless a publishable build of it is kept.
build_latest() {
  local latest
  latest=$(latest)
  [ -n "$latest" ] || return 0
  if publishable "$latest"; then
    return
  fi

  say "Building $latest for every target, as it ships; this takes a while."
  jp release build "$latest" ||
    die "$latest didn't build. Fix the build, then run \`just backfill proceed\` again, which builds $latest before it starts the next period."
}

cmd_proceed() {
  need_clone proceed
  local version
  version=$(preparing)
  [ "$(count_of "$version")" -le 1 ] ||
    die "More than one release is in preparation: $(joined "$version")."
  tools
  if [ -n "$version" ]; then
    finish "$version"
  fi
  build_latest
  cmd_next
}

cmd_revert() {
  need_clone revert
  local target=${1:-} versions reverting version branch notes
  target=${target#v}
  [[ $target =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] ||
    die "Name the release to take back, such as \`just backfill revert 0.5.0\`."

  versions=$({ tagged; preparing; } | sort -u | newest_first)
  reverting=$(for version in $versions; do
    if at_least "$version" "$target"; then
      printf '%s\n' "$version"
    fi
  done)
  printf '%s\n' "$reverting" | grep -qxF "$target" ||
    die "$target hasn't been cut, so there is nothing to take back."
  tools

  # Edits to notes in preparation come back with them, so commit them first.
  branch=$(git symbolic-ref --quiet --short HEAD || true)
  if [[ $branch == release-notes/v* ]]; then
    clean_outside_fragments
    git add -- "$FRAGMENTS"
    git diff --cached --quiet || git commit --quiet -m "docs(changelog): Edit the notes of ${branch#release-notes/v}"
  fi
  on_main

  for version in $reverting; do
    say "Taking back $version."
    # `abandon` refuses a release `origin` has tagged, which here is only the
    # stand-in.
    if git ls-remote --exit-code origin "refs/tags/v$version" >/dev/null 2>&1; then
      git push --quiet origin ":refs/tags/v$version"
    fi
    jp release abandon "$version" >/dev/null || die "Taking back $version failed."
    notes=release-notes/abandon-v$version
    if git rev-parse --quiet --verify "refs/heads/$notes" >/dev/null; then
      git merge --quiet --no-ff --no-edit -m "docs(changelog): Take back the notes of $version" "$notes"
      git branch --quiet -D "$notes"
      push_main
    fi
    mirror
    remove_build "$version"
  done

  say "Took back $(joined "$reverting") and their builds; \`just backfill next\` cuts $target again, with the notes as you left them."
}

cmd_draft() {
  local since=${1:-}
  [ -n "$since" ] ||
    die "Name the commit whose later changes to draft, such as \`just backfill draft 1a2b3c4\`."
  git rev-parse --quiet --verify "$since^{commit}" >/dev/null || die "$since names no commit."
  tools
  draft "$since..HEAD" "" "$(git show -s --format=%cs "$since")" "$(git show -s --format=%cs HEAD)"
  tidy
  say "Review the new fragments in $FRAGMENTS/, then commit them."
}

cmd_publish() {
  need_clone publish
  local preparing versions version missing='' github history theirs ours gap answer first last
  preparing=$(preparing)
  [ -z "$preparing" ] ||
    die "$preparing is in preparation; finish it with \`just backfill proceed\`, or take it back, first."
  [ -n "${JP_GITHUB_TOKEN:-}${GITHUB_TOKEN:-}" ] ||
    die "Publishing needs a GitHub token that can write the repository's contents, in JP_GITHUB_TOKEN or GITHUB_TOKEN; \`gh auth token\` prints one."
  on_main
  [ -z "$(git status --porcelain)" ] || die "Commit or discard the changes on main first."
  tools github

  versions=$(tagged)
  [ -n "$versions" ] || die "No release is finalized yet, so there is nothing to publish."
  for version in $versions; do
    publishable "$version" || missing="$missing $version"
  done
  [ -z "$missing" ] ||
    die "No publishable build is kept for$missing; build each with \`jp release build <version>\` first."

  github=$(setting github)
  history=$(setting history)
  say "Fetching GitHub's main."
  git fetch --quiet --no-tags "$github" "+refs/heads/main:refs/backfill/github"
  gap=$(git rev-list --first-parent --count "$history..refs/backfill/github")
  theirs=$(git ls-remote "$github" refs/tags/v0.1.0 | cut -f1)
  ours=$(git rev-parse --quiet --verify refs/tags/v0.1.0 || true)
  first=$(printf '%s\n' "$versions" | sed -n 1p)
  last=$(printf '%s\n' "$versions" | sed -n '$p')

  cat <<EOF

This publishes $(count_of "$versions") releases, $first to $last, to $github. It:

  1. merges GitHub's main into the trial's
  2. deletes GitHub's old v0.1.0, when it names another commit than this one's
  3. pushes every release branch and tag in one push
  4. runs \`jp release github publish\` for each release, oldest first
  5. pushes the trial's main as the branch $HISTORY_BRANCH, for a pull request
     into main

None of it can be taken back.
EOF
  if [ "$(count_of "$versions")" -le 3 ]; then
    cat <<EOF

GitHub runs the workflows of each tagged commit when one push holds three tags
or fewer, and the history's commits deploy the site on any tag. Restrict the
\`documentation\` environment to deployments from main before going on.
EOF
  fi
  printf '\nType publish to go on: '
  IFS= read -r answer || answer=
  [ "$answer" = publish ] || die "Nothing was published."

  if ! git merge --quiet --no-edit -m "chore: Merge GitHub's \`main\` into the history to release" \
    refs/backfill/github; then
    git merge --abort
    die "Merging GitHub's main conflicts; merge it by hand with \`git merge refs/backfill/github\`, commit, and run \`just backfill publish\` again. Nothing was published."
  fi
  push_main

  if [ -n "$theirs" ] && [ "$theirs" != "$ours" ]; then
    say "Deleting GitHub's old v0.1.0."
    git push --quiet "$github" :refs/tags/v0.1.0
  fi
  say "Pushing the release branches and tags."
  git push --quiet "$github" 'refs/heads/release/*:refs/heads/release/*' 'refs/tags/v*:refs/tags/v*'
  for version in $versions; do
    say "Publishing $version."
    jp release github publish "$version"
  done
  say "Pushing the history's notes as $HISTORY_BRANCH."
  git push "$github" "main:refs/heads/$HISTORY_BRANCH"

  cat <<EOF

Published $first to $last on GitHub. Their notes reach GitHub's main through
$HISTORY_BRANCH: open its pull request and merge it. It brings in $(setting branch)
too, whose own fragments ship in the first release cut after it merges, with
\`just release cut\`.
EOF
  if [ "$gap" -gt 0 ]; then
    say ""
    say "$gap changes reached GitHub's main during the trial, after $(short "$history"), and have no fragments:"
    git log --first-parent --format='  %h %s' "$history..refs/backfill/github" | sed -n '1,20p'
    [ "$gap" -le 20 ] || say "  and $((gap - 20)) more"
    say "Draft them in a checkout of main once the pull request merges, with \`just backfill draft $(short "$history")\`, so they ship in that release too."
  fi
  say ""
  say "Then apply T-1f2jmb7's rulesets, which protect the release branches and tags."
}

main() {
  cd "$(git rev-parse --show-toplevel)"
  local command=${1:-}
  [ $# -eq 0 ] || shift
  case $command in
  init) cmd_init "$@" ;;
  next) cmd_next ;;
  proceed) cmd_proceed ;;
  revert) cmd_revert "$@" ;;
  draft) cmd_draft "$@" ;;
  publish) cmd_publish ;;
  *) usage ;;
  esac
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  main "$@"
fi
