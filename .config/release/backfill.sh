# The credits of a fragment's `Credits` fields, one per line, from the file $1.
credits_of() { sed -n 's/^- \*\*[Cc][Rr][Ee][Dd][Ii][Tt][Ss]\*\*: *//p' "$1"; }

# The changes the fragments describe, as `<credit><TAB><file>` lines: each
# `Credits` value, and for a fragment at the top level without any, the commit
# that added it.
noted() {
  local file credits credit
  find "$FRAGMENTS" -type f -name '*.md' ! -path '*/highlights/*' \
    ! -name README.md ! -name overview.md |
    while IFS= read -r file; do
      credits=$(credits_of "$file")
      if [ -z "$credits" ] && [ "$(dirname "$file")" = "$FRAGMENTS" ]; then
        credits=$(git log --first-parent --diff-filter=A --format=%H -1 -- "$file" || true)
      fi
      for credit in $credits; do
        printf '%s\t%s\n' "$credit" "$file"
      done
    done
}

# Whether a fragment credits one of the changes the lines of $1 name. A hash
# matches a hash that starts with it, or that it starts with.
credited() {
  noted | awk -F '\t' -v named="$1" '
    BEGIN { count = split(tolower(named), name, "\n") }
    {
      credit = tolower($1)
      for (i = 1; i <= count; i++) {
        if (name[i] == "") continue
        if (credit == name[i]) found = 1
        if (credit !~ /^#/ && name[i] !~ /^#/ &&
          (index(credit, name[i]) == 1 || index(name[i], credit) == 1)) found = 1
      }
    }
    END { exit !found }'
}

# Go through the changes in the range $2 on HEAD's first-parent line, oldest
# first, with the fragments that credit them, read from the file $3, which holds
# what `noted` prints. A change's credit is `#<number>` for a pull request, or
# the first 12 characters of its commit's hash.
#
# - `list` prints each change, then the fragments that credit it, or `no
#   fragment`.
# - `draft` prints as Markdown each change that no fragment credits, or each one
#   the file $5 names when it's given, with its message and the files it
#   changed, and writes their credits to the file $4, one per line.
# - `authors` prints, once each, the authors of the changes the file $5 names.
# - `files` prints, once each, the fragments that credit any of the changes.
changes() {
  local mode=$1 range=$2 noted=$3 credits=${4:-/dev/null} wanted=${5:-}
  git log --first-parent --diff-merges=first-parent --reverse --numstat \
    --format='%x1e%H%x1f%cs%x1f%s%x1f%b%x1f%an%x1f' "$range" |
    awk -v FS='\037' -v mode="$mode" -v noted="$noted" -v credits="$credits" -v wanted="$wanted" '
      function trim(text) {
        gsub(/^[ \t\r]+|[ \t\r]+$/, "", text)
        return text
      }
      # The fragments that credit the change with hash h and change request r.
      function crediting(h, r,   i, found) {
        found = (r != "" && (r in by_request)) ? by_request[r] : ""
        for (i = 1; i <= hashes; i++)
          if (index(h, hash[i]) == 1)
            found = found (found == "" ? "" : "\n") hash_file[i]
        return found
      }
      # Whether the wanted credits name the change with hash h and change
      # request r.
      function is_wanted(h, r,   key) {
        if (r != "" && (r in want)) return 1
        for (key in want)
          if (key !~ /^#/ && index(h, key) == 1) return 1
        return 0
      }
      BEGIN {
        # RS applies to getline too, so it changes once the files are read.
        while ((getline entry < noted) > 0) {
          split(entry, part, "\t")
          credit = tolower(trim(part[1]))
          if (credit ~ /^#[0-9]+$/) {
            if (credit in by_request) by_request[credit] = by_request[credit] "\n" part[2]
            else by_request[credit] = part[2]
          } else if (credit != "") {
            hash[++hashes] = credit
            hash_file[hashes] = part[2]
          }
        }
        close(noted)
        if (wanted != "") {
          while ((getline entry < wanted) > 0) {
            entry = tolower(trim(entry))
            if (entry != "") want[entry] = 1
          }
          close(wanted)
        }
        RS = "\036"
      }
      {
        sub(/^\n+/, "")
        if ($0 == "") next
        h = $1; day = $2; subject = $3; body = $4; author = $5; stats = $6
        r = ""
        if (match(subject, /\(#[0-9]+\)$/))
          r = "#" substr(subject, RSTART + 2, RLENGTH - 3)
        else if (match(subject, /^Merge pull request #[0-9]+/))
          r = "#" substr(subject, RSTART + 20, RLENGTH - 20)
        credit = r != "" ? r : substr(h, 1, 12)
        found = crediting(h, r)

        if (mode == "files") {
          count = split(found, file, "\n")
          for (i = 1; i <= count; i++)
            if (file[i] != "" && !(file[i] in seen)) {
              seen[file[i]] = 1
              print file[i]
            }
          next
        }

        if (mode == "authors") {
          if (is_wanted(h, r) && !(author in authors)) {
            authors[author] = 1
            print author
          }
          next
        }

        if (mode == "list") {
          printf "%-14s %s  %s\n", credit, day, subject
          count = split(found, file, "\n")
          if (count == 0) print "               no fragment"
          for (i = 1; i <= count; i++) print "               " file[i]
          next
        }

        if (wanted != "") {
          if (!is_wanted(h, r)) next
        } else if (found != "") next

        print credit > credits
        printf "### %s (%s) %s\n\n", credit, day, subject
        count = split(body, text, "\n")
        while (count > 0 && text[count] ~ /^[ \t\r]*$/) count--
        shown = count < 20 ? count : 20
        for (i = 1; i <= shown; i++) print "> " text[i]
        if (count > shown) print "> (" count - shown " more lines)"
        if (count > 0) print ""

        count = split(stats, line, "\n")
        listed = 0
        for (i = 1; i <= count; i++) {
          if (split(line[i], column, "\t") < 3) continue
          if (++listed > 40) continue
          if (column[1] == "-") note = "binary"
          else {
            note = "+" column[1] " -" column[2]
            if (column[3] ~ /(^|\/)(Cargo|yarn|pnpm)\.lock$|(^|\/)package-lock\.json$|\.snap$|(^|\/)(fixtures|cassettes|snapshots)\//)
              note = note ", generated"
            else if (column[1] + column[2] > 500) note = note ", large"
          }
          if (listed == 1) print "Files:\n"
          printf "- `%s` (%s)\n", column[3], note
        }
        if (listed > 40) print "- and " listed - 40 " more files"
        if (listed > 0) print ""
      }'
}

# What a prompt says about where release $1's code is.
code_paragraph() {
  say "The code of $1, as it was at its last change, is in \`$CODE_MOUNT/\`. The rest of this workspace is JP today, which is later than $1: read the release's code only in \`$CODE_MOUNT/\`."
}

# Draft fragments in an interactive conversation, for the changes of release $1
# in the range $2, which reached main between the days $3 and $4: the changes
# no fragment credits, or the ones the file $5 names when it isn't empty. The
# file $6, when not empty, holds more of the prompt, put before the changes. The
# release's code is checked out in the worktree $7, or is the workspace's own
# when $7 is empty. The conversation is titled $8. The other arguments go to
# `jp query`.
draft() {
  local version=$1 range=$2 from=$3 until=$4 wanted=$5 extra=$6 code=$7 title=$8
  shift 8
  local work count paragraph hint='' noun=changes previous since
  work=$(mktemp -d)
  noted >"$work/noted"
  : >"$work/credits"
  changes draft "$range" "$work/noted" "$work/credits" "$wanted" >"$work/changes.md"
  count=$(grep -c . "$work/credits" || true)
  if [ "$count" -eq 0 ]; then
    rm -rf "$work"
    [ -z "$code" ] || hint="; \`just backfill changes\` lists them"
    if [ -n "$wanted" ]; then
      say "None of the changes named is among the changes of $version$hint."
    else
      say "Every change of $version has a fragment already$hint."
    fi
    return
  fi

  if [ -n "$code" ]; then
    paragraph=$(code_paragraph "$version")
  else
    paragraph="The code of $version is this workspace's."
  fi
  # What the notes compare against: the newest release before them.
  previous=$(latest)
  if [ -n "$previous" ]; then
    since="The notes describe what changed since JP $previous, the release before them. A feature new in $version is \`added\`, however it changed along the way, and only a change that breaks what $previous shipped gets an upgrade section."
  else
    since="$version is JP's first release, so every fragment is \`added\`, and none has an upgrade section: nothing in it breaks an earlier release."
  fi
  {
    sed -e "s/{version}/$version/g" -e "s/{from}/$from/g" -e "s/{until}/$until/g" \
      -e "s|^{code}\$|$paragraph|" -e "s|^{previous}\$|$since|" "$HERE/backfill.md"
    if [ -n "$extra" ]; then
      printf '\n'
      cat "$extra"
    fi
    printf '\n## The changes, oldest first\n\n'
    cat "$work/changes.md"
  } >"$work/prompt.md"

  [ "$count" -ne 1 ] || noun=change
  say "Drafting fragments for $count $noun of $version. Each fragment written, revised, or deleted is shown first: y does it, e edits it first, r skips it with a reply for the model. ^C stops, and the fragments written stay."
  if ! jp --cfg "$(persona release-notes)" query --new --local --no-edit --title "$title" \
    ${code:+--mount "$CODE_MOUNT=$code"} ${1+"$@"} "@$work/prompt.md"; then
    say "Drafting stopped."
  fi
  rm -rf "$work"
}

# Discard the period's notes: its uncommitted drafts, and the fragments at the
# top of the fragments directory that credit one of its changes, such as the
# ones `revert` brings back. Highlights, and the fragments set aside for
# `--redo`, stay.
discard_period() {
  local work file paths=()
  git restore --source=HEAD --staged --worktree -- "$FRAGMENTS"
  git clean -fdq -- "$FRAGMENTS"
  work=$(mktemp -d)
  noted >"$work/noted"
  changes files "$(setting period.range)" "$work/noted" >"$work/files"
  while IFS= read -r file; do
    if [ "$(dirname "$file")" = "$FRAGMENTS" ]; then
      paths+=("$file")
    fi
  done <"$work/files"
  rm -rf "$work"
  if [ ${#paths[@]} -eq 0 ]; then
    say "Discarded the drafts of $(setting period.version)."
    return
  fi
  git rm --quiet -- "${paths[@]}"
  if [ ${#paths[@]} -eq 1 ]; then
    say "Discarded the drafts of $(setting period.version), and its fragment committed already."
  else
    say "Discarded the drafts of $(setting period.version), and its ${#paths[@]} fragments committed already."
  fi
}

# Set aside the fragments the lines of $3 name, to be drafted again: move them
# to `.git/backfill/redo`, write the credits of the changes they describe to
# the file $1/wanted, and their text, with the reason $2, to the file
# $1/extra.md for the prompt.
set_aside() {
  local work=$1 why=$2 list=$3 aside file credits
  while IFS= read -r file; do
    file=${file#./}
    [ -n "$file" ] || continue
    [ -f "$file" ] || die "$file is no fragment here."
    [ "$(dirname "$file")" = "$FRAGMENTS" ] || die "$file isn't at the top of $FRAGMENTS/, where drafts are."
    [ -n "$(credits_of "$file")" ] || die "$file credits no change, so there is nothing to draft it from."
  done <<<"$list"

  aside=$(git rev-parse --git-path backfill/redo)
  rm -rf "$aside"
  mkdir -p "$aside"
  : >"$work/wanted"
  {
    printf '## Fragments to write again\n\n'
    printf 'These fragments were set aside to be written again. Write new fragments for the changes they credit, which are listed below.\n'
    if [ -n "$why" ]; then
      printf '\nThe reason given: %s\n' "$why"
    fi
  } >"$work/extra.md"
  while IFS= read -r file; do
    file=${file#./}
    [ -n "$file" ] || continue
    credits=$(credits_of "$file")
    printf '%s\n' "$credits" >>"$work/wanted"
    # shellcheck disable=SC2016 # The backticks fence Markdown, not a command.
    printf '\n### %s\n\n````markdown\n%s\n````\n' "$(basename "$file")" "$(cat "$file")" >>"$work/extra.md"
    mv "$file" "$aside/"
  done <<<"$list"
}

# Put each fragment set aside back where it was, unless a fragment credits the
# changes it did. The ones replaced stay set aside, to compare.
bring_back() {
  local aside file back='' kept=''
  aside=$(git rev-parse --git-path backfill/redo)
  for file in "$aside"/*.md; do
    [ -e "$file" ] || continue
    if credited "$(credits_of "$file")"; then
      kept=1
    elif [ -e "$FRAGMENTS/$(basename "$file")" ]; then
      say "Kept $(basename "$file") set aside: no fragment credits its changes, but a new one took its name."
    else
      mv "$file" "$FRAGMENTS/"
      back="$back $(basename "$file")"
    fi
  done
  [ -z "$back" ] || say "No new fragment credits the changes of$back, so they're back in $FRAGMENTS/."
  [ -z "$kept" ] || say "The fragments replaced are kept in $aside, to compare."
}

# Say how many of the period's changes have no fragment yet.
period_summary() {
  local work total missing
  work=$(mktemp -d)
  noted >"$work/noted"
  changes list "$(setting period.range)" "$work/noted" >"$work/list"
  total=$(grep -c '^[^ ]' "$work/list" || true)
  missing=$(grep -c ' no fragment$' "$work/list" || true)
  rm -rf "$work"
  say "$missing of the $total changes of $(setting period.version) have no fragment: \`just backfill changes\` lists them, and \`just backfill cut\` cuts the release once its notes are ready."
}

# Fill the prompt template $1, beside this script, for release $2, whose
# changes reached main between the days $3 and $4.
template() {
  local paragraph
  paragraph=$(code_paragraph "$2")
  sed -e "s/{version}/$2/g" -e "s/{from}/$3/g" -e "s/{until}/$4/g" \
    -e "s|{wiki}|$CODE_MOUNT/$WIKI|g" -e "s|{fragments}|$FRAGMENTS|g" \
    -e "s|{guide}|$SITE/v$2/wiki|g" -e "s|^{code}\$|$paragraph|" "$HERE/$1"
}

# The release in preparation, with its notes branch checked out: the release
# the docs and highlight steps write for.
guided_release() {
  local version branch
  version=$(preparing)
  [ -n "$version" ] || die "No release is in preparation; \`just backfill cut\` cuts one."
  [ "$(count_of "$version")" -le 1 ] || die "More than one release is in preparation: $(joined "$version")."
  [ "$version" = "$(setting period.version)" ] ||
    die "$version is in preparation, but the period in drafting is $(setting period.version)'s."
  branch=$(git symbolic-ref --quiet --short HEAD || true)
  if [ "$branch" != "release-notes/v$version" ]; then
    [ -z "$(git status --porcelain)" ] ||
      die "Commit or discard the changes on ${branch:-the detached HEAD} first."
    git checkout --quiet "release-notes/v$version"
  fi
  printf '%s\n' "$version"
}

# Check out the tip of release $1's branch in the worktree beside the clone,
# where its guide is written, keeping the changes a stopped conversation left
# there.
guide_tree() {
  local dir branch
  dir=$(code_dir)
  branch=refs/heads/release/${1%.*}
  if [ -e "$dir" ] && [ "$(git -C "$dir" rev-parse HEAD)" = "$(git rev-parse "$branch")" ]; then
    return
  fi
  [ ! -e "$dir" ] || [ -z "$(git -C "$dir" status --porcelain)" ] ||
    die "$dir holds changes, and isn't at the tip of $1's release branch; commit or discard them there first."
  prepare_code "$branch"
}

# Apply the patch on standard input in the worktree $1, passing the other
# arguments to `git apply --3way`, and show what git says only when it fails:
# it notes every new file it applies without a merge.
apply_in() {
  local dir=$1 said
  shift
  if ! said=$(git -C "$dir" apply --3way "$@" 2>&1); then
    printf '%s\n' "$said" >&2
    return 1
  fi
}

# Set the `Date` field of the wiki page $1 to the day $2.
date_page() {
  local dated
  dated=$(awk -v day="$2" '
    !done && /^- \*\*Date\*\*:/ { print "- **Date**: " day; done = 1; next }
    { print }' "$1")
  printf '%s\n' "$dated" >"$1"
}

# Commit the changes the worktree holds to release $1's guide, dated at its
# last day, with the `Date` of each page they add set to that day, and move its
# release branch to the commit. $2 is the commit's message.
save_guide() {
  local version=$1 message=$2 dir branch day at file
  dir=$(code_dir)
  branch=refs/heads/release/${version%.*}
  [ -e "$dir" ] || return 0
  [ "$(git -C "$dir" rev-parse HEAD)" = "$(git rev-parse "$branch")" ] || return 0
  [ -n "$(git -C "$dir" status --porcelain -- "$WIKI")" ] || return 0

  day=$(git show -s --format=%cs "$(start_of "$version")")
  git -C "$dir" ls-files --others --exclude-standard -- "$WIKI" |
    while IFS= read -r file; do
      case $file in
      *.md) date_page "$dir/$file" "$day" ;;
      esac
    done
  at="$(noon "$day") +0000"
  git -C "$dir" add -- "$WIKI"
  env GIT_AUTHOR_DATE="$at" GIT_COMMITTER_DATE="$at" git -C "$dir" commit --quiet -m "$message"
  git update-ref "$branch" "$(git -C "$dir" rev-parse HEAD)"
  mirror
}

# Start release $1's guide with the one written for the release before it: the
# changes that release's branch made to the wiki, applied in the worktree and
# committed on $1's branch. Before any guide exists, start the wiki with
# `main`'s epoch, so the ids of its pages can't collide with `main`'s. Records
# where $1's own writing starts as refs/backfill/guide/$1/carried.
carry_guide() {
  local version=$1 dir branch previous base='' exclude='' message
  dir=$(code_dir)
  branch=refs/heads/release/${version%.*}
  [ -z "$(git -C "$dir" diff --name-only --diff-filter=U)" ] ||
    die "$dir holds conflicts in the guide; resolve them there, then run \`just backfill docs\` again."
  # Started already: the branch has changed the wiki since the release started.
  if ! git diff --quiet "$(start_of "$version")" "$branch" -- "$WIKI"; then
    return
  fi

  previous=$(latest)
  [ -z "$previous" ] || base=$(start_of "$previous")
  if [ -n "$base" ] && ! git diff --quiet "$base" "v$previous" -- "$WIKI"; then
    # Changes in the worktree are that guide, its conflicts resolved by hand.
    if [ -z "$(git -C "$dir" status --porcelain -- "$WIKI")" ]; then
      say "Bringing in the guide written for $previous."
      [ ! -e "$dir/$WIKI/.epoch" ] || exclude=--exclude=$WIKI/.epoch
      git diff --binary "$base" "v$previous" -- "$WIKI" | apply_in "$dir" ${exclude:+"$exclude"} ||
        die "Bringing in $previous's guide conflicts, most likely in $WIKI/.order.json, which both trees hold. In $dir, bring in the rest with \`git diff --binary $(short "$base") v$previous -- $WIKI ':(exclude)$WIKI/.order.json' ':(exclude)$WIKI/.epoch' | git apply --3way\`, add the guide's pages that \`git show v$previous:$WIKI/.order.json\` lists to the tree's own .order.json, then run \`just backfill docs\` again."
    fi
    message="docs(wiki): Carry the guide of $previous"
  else
    mkdir -p "$dir/$WIKI"
    [ -e "$dir/$WIKI/.epoch" ] || git show "main:$WIKI/.epoch" >"$dir/$WIKI/.epoch"
    message="docs(wiki): Start the guide of $version"
  fi
  save_guide "$version" "$message"
  git update-ref "refs/backfill/guide/$version/carried" "$branch"
}

# Keep the guide written for release $1, which is being taken back, as
# refs/backfill/guide/$1/{base,tip}, for the next cut of $1 to bring back.
keep_guide() {
  local version=$1 branch start base
  branch=refs/heads/release/${version%.*}
  start=$(start_of "$version")
  if [ -z "$start" ] || git diff --quiet "$start" "$branch" -- "$WIKI"; then
    return
  fi
  base=$(git rev-parse --quiet --verify "refs/backfill/guide/$version/carried") || base=$start
  git update-ref "refs/backfill/guide/$version/base" "$base"
  git update-ref "refs/backfill/guide/$version/tip" "$branch"
  git update-ref -d "refs/backfill/guide/$version/carried" 2>/dev/null || true
}

# Bring back the guide written for release $1 before it was taken back: apply
# it in the worktree and commit it on $1's branch.
restore_guide() {
  local version=$1 dir base tip day file
  dir=$(code_dir)
  tip=$(git rev-parse --quiet --verify "refs/backfill/guide/$version/tip") || return 0
  base=$(git rev-parse "refs/backfill/guide/$version/base")
  # As in carry_guide, changes in the worktree are that guide, resolved by hand.
  if [ -z "$(git -C "$dir" status --porcelain -- "$WIKI")" ] &&
    ! git diff --quiet "$base" "$tip" -- "$WIKI"; then
    say "Bringing back the guide written for $version before it was taken back."
    git diff --binary "$base" "$tip" -- "$WIKI" | apply_in "$dir" ||
      die "Bringing back $version's guide conflicts; resolve it in $dir, then run \`just backfill docs\` again."
  fi
  # The pages it added are dated at the release's last day, which the new cut
  # can have moved.
  day=$(git show -s --format=%cs "$(start_of "$version")")
  git diff --name-only --diff-filter=A "$base" "$tip" -- "$WIKI" |
    while IFS= read -r file; do
      case $file in
      *.md) [ ! -e "$dir/$file" ] || date_page "$dir/$file" "$day" ;;
      esac
    done
  save_guide "$version" "docs(wiki): Bring back the guide of $version"
  git update-ref -d "refs/backfill/guide/$version/tip"
  git update-ref -d "refs/backfill/guide/$version/base"
}

# Bring the guide written for release $1, the last, into `main`, unless a commit
# there brought it in already.
guide_to_main() {
  local version=$1 start message
  message="docs(wiki): Write the user guide as of $version"
  start=$(start_of "$version")
  if git diff --quiet "$start" "v$version" -- "$WIKI" ||
    [ -n "$(git log -1 --format=%H --fixed-strings --grep="$message" main)" ]; then
    return
  fi
  say "Bringing $version's guide into main."
  git diff --binary "$start" "v$version" -- "$WIKI" | apply_in . --exclude="$WIKI/.epoch" ||
    die "Bringing $version's guide into main conflicts; resolve it, commit it with \`git commit -m '$message'\`, and run \`just backfill publish\` again. Nothing was published."
  git commit --quiet -m "$message"
  push_main
}

# Whether the guide for $1, `<version>/<item>`, is written or needs none.
documented() { git config --get-all jp-backfill.documented 2>/dev/null | grep -xF "$1" >/dev/null; }

mark_documented() { documented "$1" || git config --add jp-backfill.documented "$1"; }

# Keep the `documented` records the awk program $1 prints, which reads $2 as
# `value`.
keep_documented() {
  local kept record
  kept=$(git config --get-all jp-backfill.documented 2>/dev/null | awk -v value="$2" "$1" || true)
  git config --unset-all jp-backfill.documented 2>/dev/null || true
  while IFS= read -r record; do
    if [ -n "$record" ]; then
      git config --add jp-backfill.documented "$record"
    fi
  done <<<"$kept"
}

# shellcheck disable=SC2016 # The `$0` belongs to the awk program.
unmark_documented() { keep_documented '$0 != value' "$1"; }

# The item of release $1's guide in progress, if any.
current_item() {
  local current
  current=$(setting docs.current)
  case $current in
  "$1"/*) printf '%s\n' "${current#"$1"/}" ;;
  esac
}

clear_current() { git config --unset jp-backfill.docs.current 2>/dev/null || true; }

# Forget which parts of release $1's guide are written, for a release being
# taken back: a new cut can change its entries, and the code they describe.
forget_docs() {
  # shellcheck disable=SC2016 # The `$0` belongs to the awk program.
  keep_documented 'index($0, value) != 1' "$1/"
  if [ -n "$(current_item "$1")" ]; then
    clear_current
  fi
}

# How many of the period's changes no entry credits.
unnoted() {
  local work count
  work=$(mktemp -d)
  noted >"$work/noted"
  count=$(changes list "$(setting period.range)" "$work/noted" | grep -c ' no fragment$' || true)
  rm -rf "$work"
  printf '%s\n' "$count"
}

# The items of release $1's guide, in order: the entries of its notes whose
# changes can change what users do, by file name, then `rest`, its changes
# without notes, when it has any.
guide_items() {
  local file name type
  for file in "$FRAGMENTS/$1"/*.md; do
    [ -e "$file" ] || continue
    name=$(basename "$file")
    type=${name%.md}
    type=${type##*.}
    case " $GUIDED " in
    *" $type "*) printf '%s\n' "$name" ;;
    esac
  done
  if [ "$(unnoted)" -gt 0 ]; then
    printf '%s\n' rest
  fi
}

# The items of release $1's guide not written yet, in order.
pending_items() {
  local item
  guide_items "$1" | while IFS= read -r item; do
    if ! documented "$1/$item"; then
      printf '%s\n' "$item"
    fi
  done
}

# The item $1 as a sentence names it.
item_label() {
  if [ "$1" = rest ]; then
    say "the changes without notes"
  else
    say "$1"
  fi
}

# The items read from standard input, as a sentence lists them.
item_labels() {
  local item labels=''
  while IFS= read -r item; do
    [ -n "$item" ] || continue
    labels="$labels${labels:+, }$(item_label "$item")"
  done
  printf '%s\n' "$labels"
}

# Whether the worktree holds changes to the guide not committed yet.
guide_changed() { [ -n "$(git -C "$(code_dir)" status --porcelain -- "$WIKI")" ]; }

# Run a conversation of the docs or highlight step, titled $2, with the prompt
# in the file $3. The wiki tools read the guide of the release in preparation,
# and write it when $1 is `write`. The other arguments go to `jp query`.
guide_conversation() {
  local access=$1 title=$2 prompt=$3 dir mode='' tool mounts=()
  shift 3
  dir=$(code_dir)
  [ "$access" != write ] || mode=:rw
  # Each tool gets a mount of its own, so no two grant one tool different modes.
  for tool in $TREE_READERS; do
    mounts+=(--mount "$tool:$CODE_MOUNT=$dir")
  done
  for tool in $GUIDE_WRITERS; do
    mounts+=(--mount "$tool:$CODE_MOUNT=$dir$mode")
  done
  # The wiki tools work on the release's wiki, and check its links against the
  # RFDs and tickets the release's tree holds.
  jp --cfg "$(persona release-docs)" \
    --cfg "plugins.command.wiki.options.dir=$CODE_MOUNT/$WIKI" \
    --cfg "plugins.command.rfd.options.dir=$CODE_MOUNT/docs/rfd" \
    --cfg "plugins.command.ticket.options.dir=$CODE_MOUNT/docs/ticket" \
    query --new --local --no-edit --title "$title" "${mounts[@]}" ${1+"$@"} \
    "@$prompt" || say "The conversation stopped."
}

# What a prompt says when a conversation about the same part of the guide has
# run before, when $1 is set.
again_paragraph() {
  [ -n "$1" ] || return 0
  cat <<EOF

An earlier conversation about this may have written guide pages for it
already: read them before writing, and carry on from them.
EOF
}

# Write the guide for the entry $2 of release $1's notes in a conversation. $3
# is set when a conversation about it has run before. The other arguments go to
# `jp query`.
document_entry() {
  local version=$1 file=$2 again=$3 work
  shift 3
  work=$(mktemp -d)
  credits_of "$file" >"$work/wanted"
  {
    template docs.md "$version" "$(setting period.from)" "$(setting period.until)"
    cat <<EOF

## The change

Its entry in the release notes, \`$file\`:

EOF
    sed 's/^/> /' "$file"
    cat <<EOF

When a guide page covers this change, end the first paragraph of the entry with
a link to the page, \` ([guide]($SITE/v$version/wiki/<page>))\`, where \`<page>\` is
the page's file name without \`.md\`; change the entry with \`fs_modify_file\`.
When the change needs no page, say why, and change nothing.
EOF
    again_paragraph "$again"
    printf '\nThe changes the entry credits, oldest first:\n\n'
    changes draft "$(setting period.range)" /dev/null /dev/null "$work/wanted"
  } >"$work/prompt.md"
  guide_conversation write "$version: guide for $(basename "$file")" "$work/prompt.md" ${1+"$@"}
  rm -rf "$work"
}

# Look for guide pages that release $1's changes without notes change, in a
# conversation. $2 is set when a conversation about them has run before. The
# other arguments go to `jp query`.
document_rest() {
  local version=$1 again=$2 work
  shift 2
  work=$(mktemp -d)
  noted >"$work/noted"
  changes draft "$(setting period.range)" "$work/noted" /dev/null '' >"$work/changes.md"
  {
    template docs.md "$version" "$(setting period.from)" "$(setting period.until)"
    cat <<EOF

## Changes without release notes

These changes have no entry in the release notes of $version, so people using JP
weren't expected to notice them. Check whether any of them still changes what a
guide page says, and update the page if so; most need nothing. Name the changes
that did.
EOF
    again_paragraph "$again"
    printf '\n'
    cat "$work/changes.md"
  } >"$work/prompt.md"
  guide_conversation write "$version: guide for the changes without notes" "$work/prompt.md" ${1+"$@"}
  rm -rf "$work"
}

# Say what can follow a conversation about the item $1 of the guide.
after_conversation() {
  local name
  name=$(item_label "$1")
  cat <<EOF

The changes to the guide for $name stay uncommitted in $(code_dir)/$WIKI
until you go on. From here:

  - \`jp query\` continues the conversation, and \`just backfill docs\` starts
    another about $name
  - edit the guide's pages there yourself, if you like
  - \`just backfill docs proceed\` commits the guide for $name, and starts
    the next entry
  - \`just backfill docs skip\` notes that the guide needs nothing for $name,
    and starts the next
  - \`just backfill docs finish\` commits it, and notes that the rest need none
EOF
}

# Start a conversation about the item $2 of release $1's guide, and make it the
# one in progress. $3 is set when a conversation about it has run before. The
# other arguments go to `jp query`.
start_item() {
  local version=$1 item=$2 again=$3 left
  shift 3
  if [ "$item" = rest ] && [ "$(unnoted)" -eq 0 ]; then
    clear_current
    say "Every change of $version has an entry in its notes, so there are no changes without notes for the guide."
    return
  fi
  git config jp-backfill.docs.current "$version/$item"
  left=$(pending_items "$version" | grep -vxF "$item" | item_labels || true)
  if [ -n "$left" ]; then
    say "Writing the guide for $(item_label "$item"); left after it: $left."
  else
    say "Writing the guide for $(item_label "$item"), the last part of $version's guide."
  fi
  if [ "$item" = rest ]; then
    document_rest "$version" "$again" ${1+"$@"}
  else
    document_entry "$version" "$FRAGMENTS/$version/$item" "$again" ${1+"$@"}
  fi
  after_conversation "$item"
}

# Start the conversation about the next item of release $1's guide not written
# yet, or say the guide is done. The other arguments go to `jp query`.
next_item() {
  local version=$1 item
  shift
  item=$(pending_items "$version" | sed -n 1p)
  if [ -z "$item" ]; then
    say "The guide of $version is done, and committed on release/${version%.*}. \`just backfill highlight <entry>\` writes a highlight, and \`just backfill proceed\` finalizes $version."
    return
  fi
  start_item "$version" "$item" '' ${1+"$@"}
}

# Commit the guide written for the item $2 of release $1, and note that it's
# written.
commit_item() {
  local version=$1 item=$2 changed=''
  if guide_changed; then
    changed=1
  fi
  if [ "$item" = rest ]; then
    save_guide "$version" "docs(wiki): Write the guide for the changes of $version without notes"
  else
    save_guide "$version" "docs(wiki): Write the guide for ${item%.md}"
  fi
  mark_documented "$version/$item"
  clear_current
  if [ -n "$changed" ]; then
    say "Committed the guide for $(item_label "$item")."
  else
    say "The guide needed no change for $(item_label "$item")."
  fi
}

cmd_docs() {
  need_clone docs
  need_period
  local action=start item='' version current again='' left
  case ${1:-} in
  proceed | skip | finish)
    action=$1
    shift
    ;;
  '' | -*) ;;
  *)
    action=open
    item=$(basename "$1")
    shift
    case $item in
    rest | *.md) ;;
    *) item=$item.md ;;
    esac
    ;;
  esac
  [ "${1:-}" != -- ] || shift
  version=$(guided_release)
  tools docs
  guide_tree "$version"
  carry_guide "$version"
  restore_guide "$version"

  current=$(current_item "$version")
  if [ -n "$current" ] && [ "$current" != rest ] && [ ! -f "$FRAGMENTS/$version/$current" ]; then
    say "$current is no entry of $version's notes any more, so its guide is no longer in progress."
    clear_current
    current=''
  fi
  # Without an entry in progress, changes to the guide, such as edits made by
  # hand, are committed apart from any entry's.
  if [ -z "$current" ]; then
    save_guide "$version" "docs(wiki): Edit the guide of $version"
  fi

  case $action in
  start)
    if [ -n "$current" ]; then
      start_item "$version" "$current" again ${1+"$@"}
    else
      next_item "$version" ${1+"$@"}
    fi
    ;;
  open)
    if [ "$item" != rest ] && [ ! -f "$FRAGMENTS/$version/$item" ]; then
      die "$item is no entry of $version's notes."
    fi
    if [ -n "$current" ] && [ "$current" != "$item" ]; then
      die "The guide for $(item_label "$current") is in progress: \`just backfill docs proceed\` commits it, and \`just backfill docs skip\` notes that the guide needs nothing for it."
    fi
    if [ "$current" = "$item" ] || documented "$version/$item"; then
      again=again
    fi
    unmark_documented "$version/$item"
    start_item "$version" "$item" "$again" ${1+"$@"}
    ;;
  proceed)
    if [ -n "$current" ]; then
      commit_item "$version" "$current"
    fi
    next_item "$version" ${1+"$@"}
    ;;
  skip)
    [ -n "$current" ] || die "No entry's guide is in progress; \`just backfill docs\` starts the next."
    if guide_changed; then
      die "$(code_dir)/$WIKI holds changes to the guide for $(item_label "$current"): \`just backfill docs proceed\` commits them, or discard them there to skip it."
    fi
    mark_documented "$version/$current"
    clear_current
    say "Noted that the guide needs nothing for $(item_label "$current")."
    next_item "$version" ${1+"$@"}
    ;;
  finish)
    if [ -n "$current" ]; then
      commit_item "$version" "$current"
    fi
    left=$(pending_items "$version")
    if [ -n "$left" ]; then
      while IFS= read -r item; do
        mark_documented "$version/$item"
      done <<<"$left"
      say "Noted that the rest of $version's guide needs no change: $(printf '%s\n' "$left" | item_labels)."
    fi
    say "The guide of $version is done, and committed on release/${version%.*}. \`just backfill highlight <entry>\` writes a highlight, and \`just backfill proceed\` finalizes $version."
    ;;
  esac
}

cmd_highlight() {
  need_clone highlight
  need_period
  local version file work
  [ $# -ge 1 ] && [ "$1" != -- ] ||
    die "Name the entry to write a highlight about, such as \`just backfill highlight $FRAGMENTS/<version>/<entry>.md\`."
  version=$(guided_release)
  file=$FRAGMENTS/$version/$(basename "$1")
  shift
  [ "${1:-}" != -- ] || shift
  [ -f "$file" ] || die "$file is no entry of $version's notes."
  tools docs
  guide_tree "$version"

  work=$(mktemp -d)
  credits_of "$file" >"$work/wanted"
  {
    template highlight.md "$version" "$(setting period.from)" "$(setting period.until)"
    cat <<EOF

## The change

Its entry in the release notes, \`$file\`:

EOF
    sed 's/^/> /' "$file"
    printf '\nIts authors:\n\n'
    changes authors "$(setting period.range)" /dev/null /dev/null "$work/wanted" | sed 's/^/- /'
    printf '\nIts credits:\n\n'
    sed 's/^/- /' "$work/wanted"
    printf '\nThe changes the entry credits, oldest first:\n\n'
    changes draft "$(setting period.range)" /dev/null /dev/null "$work/wanted"
  } >"$work/prompt.md"
  guide_conversation read "$version: highlight for $(basename "$file")" "$work/prompt.md" ${1+"$@"}
  rm -rf "$work"
}

cmd_init() {
  local dir=${1:-} root branch github main day common standin clone id
  if in_clone; then
    die "This is the trial's clone; run \`just backfill init\` in the checkout to release from."
  fi

  root=$(pwd)
  branch=$(git symbolic-ref --quiet --short HEAD) ||
    die "HEAD is detached; check out the branch to release from."
  github=$(git remote get-url origin 2>/dev/null) ||
    die "This checkout has no \`origin\` remote to read GitHub's main from."

  say "Fetching GitHub's main."
  git fetch --quiet --no-tags origin main
  main=$(git rev-parse --verify refs/remotes/origin/main)
  day=$(git show -s --format=%cs "$main")
  git merge-base --is-ancestor "$main" HEAD ||
    die "$branch lacks commits of GitHub's main; merge them in first, with \`git merge origin/main\`."

  [ -n "$dir" ] || dir=$(dirname "$root")/jp-backfill
  [ ! -e "$dir" ] || die "$dir exists already; delete it, or name another directory with \`just backfill init <dir>\`."
  common=$(cd "$(git rev-parse --git-common-dir)" && pwd)
  id=$(new_id)
  while [ "$id" = "$(workspace_id)" ]; do id=$(new_id); done

  mkdir -p "$dir"
  dir=$(cd "$dir" && pwd)
  standin=$dir/origin.git
  clone=$dir/jp
  say "Making the trial in $dir."
  git init --quiet --bare --initial-branch=main "$standin"
  git push --quiet "$standin" "$main:refs/heads/main"
  git clone --quiet "$standin" "$clone"
  (
    cd "$clone"
    git fetch --quiet --no-tags "$common" "+refs/heads/$branch:refs/backfill/source"
    trim_source "$branch"
    git merge --quiet --no-ff --no-edit \
      -m "chore: Merge \`$branch\` into the history to release" refs/backfill/trimmed
    printf '%s\n%s\n' "$ID_PREAMBLE" "$id" >.jp/.id
    git update-index --skip-worktree .jp/.id
    git config jp-backfill.source "$root"
    git config jp-backfill.git "$common"
    git config jp-backfill.branch "$branch"
    git config jp-backfill.history "$main"
    git config jp-backfill.github "$github"
    git push --quiet origin main
  )

  cat <<EOF

Made the trial in $dir:

  origin.git  stands in for GitHub, with GitHub's main as of $(short "$main") ($day)
  jp          a clone of it, whose main merges $branch without its own fragments

The history to release runs to $(short "$main"). Release it a period at a time,
in the clone:

  cd $clone
  just backfill next

The clone is a JP workspace of its own, so its conversations and builds stay
apart from this checkout's. To back out at any time, delete the trial and the
clone's JP data:

  rm -rf "$dir" "$(data_dir)/workspace/jp-$id"
EOF
}

cmd_next() {
  need_clone next
  local fresh=''
  if [ "${1:-}" = --fresh ]; then
    fresh=1
    shift
  fi
  [ "${1:-}" != -- ] || shift
  local preparing history history_day latest start prev_end='' prev_day='' version suggested
  local day end range eof='' count from
  preparing=$(preparing)
  [ -z "$preparing" ] ||
    die "$preparing is in preparation: finish it with \`just backfill proceed\`, or take it back with \`just backfill revert $preparing\`."
  on_main
  clean_outside_fragments
  tools
  refresh

  history=$(setting history)
  history_day=$(git show -s --format=%cs "$history")
  latest=$(latest)
  version=$(next_version)
  if [ -n "$latest" ]; then
    start=$(start_of "$latest")
    prev_end=$(git rev-parse "$start^")
    prev_day=$(git show -s --format=%cs "$start")
    [ "$prev_end" != "$history" ] ||
      die "The history is released up to $(short "$history"), GitHub's main as \`init\` found it; end the trial with \`just backfill publish\`."
    suggested=$(day_after "$prev_day" "$PERIOD")
    say "$version releases the changes after $prev_day, where $latest ends."
  else
    if git cat-file -e "$FIRST_END^{commit}" 2>/dev/null; then
      suggested=$(git show -s --format=%cs "$FIRST_END")
    else
      suggested=$(day_after "$(git log --max-parents=0 --format=%cs "$history" | sed -n 1p)" "$PERIOD")
    fi
    say "$version releases the start of JP's history."
  fi
  if [ "$(setting period.version)" = "$version" ]; then
    suggested=$(setting period.until)
    if [ -n "$fresh" ]; then
      say "$version is in drafting, ending on $suggested."
    else
      say "$version is in drafting, ending on $suggested; its drafts stay."
    fi
  fi
  if [[ $suggested > $history_day ]]; then
    suggested=$history_day
  fi
  say "Suggested last day: $suggested"

  while :; do
    printf 'Last day of %s, or Enter for %s: ' "$version" "$suggested"
    if ! IFS= read -r day; then
      eof=1
      day=
      printf '\n'
    fi
    day=${day:-$suggested}
    if ! is_day "$day"; then
      say "$day isn't a day written YYYY-MM-DD."
    elif [ -n "$prev_day" ] && [[ ! $day > $prev_day ]]; then
      say "$version has to end after $prev_day, where $latest ends."
    else
      if [[ $day > $history_day ]]; then
        say "The history ends on $history_day, so $version ends there."
        day=$history_day
      fi
      end=$(git rev-list --first-parent -n 1 --before="$day 23:59:59" "$history")
      if [ -z "$end" ]; then
        say "No commit reached main by $day."
      elif [ -n "$prev_end" ] && git merge-base --is-ancestor "$end" "$prev_end"; then
        say "No change reached main between $prev_day and $day; name a later day."
      else
        break
      fi
    fi
    [ -z "$eof" ] || die "No day to end $version on."
  done

  range=$end
  [ -z "$prev_end" ] || range=$prev_end..$end
  count=$(git rev-list --first-parent --count "$range")
  from=$prev_day
  [ -n "$from" ] || from="the start of JP's history"
  record_period "$version" "$range" "$end" "$from" "$day"
  say "$version ends at $(short "$end"), $(git show -s --format='%cs: %s' "$end"), with $count changes."

  prepare_code "$end"
  if [ -n "$fresh" ]; then
    discard_period
  fi
  draft "$version" "$range" "$from" "$day" '' '' "$(code_dir)" "$version: draft notes" ${1+"$@"}
  period_summary
}

cmd_changes() {
  need_clone changes
  need_period
  local work
  work=$(mktemp -d)
  noted >"$work/noted"
  say "The changes of $(setting period.version), from $(setting period.from) to $(setting period.until), and the fragments that credit them:"
  say ""
  changes list "$(setting period.range)" "$work/noted"
  rm -rf "$work"
}

cmd_cut() {
  need_clone cut
  need_period
  local version end day preparing
  version=$(setting period.version)
  end=$(setting period.end)
  day=$(setting period.until)
  preparing=$(preparing)
  [ -z "$preparing" ] ||
    die "$preparing is cut already; its notes are on release-notes/v$preparing."
  on_main
  clean_outside_fragments
  tools
  tidy
  git add -- "$FRAGMENTS"
  if ! git diff --cached --quiet; then
    git commit --quiet -m "docs(changelog): Draft the notes of $version"
    push_main
  fi

  say "Cutting $version at $(short "$end"), dated $day."
  dated_jp "$day" release cut --at "$end" --version "$version" >/dev/null ||
    die "The cut failed for the reason above. The drafts are committed on main, and \`just backfill next\` can end $version on another day."
  mirror

  say "Building $version for this Mac, to check that it builds."
  if ! env JP_RELEASE_TARGETS=host "$JP" release build "$version" --quick >/dev/null; then
    die "$version doesn't build at $(short "$end"). Take it back with \`just backfill revert $version\` and end it on another day, or fix the build and run \`jp release build $version --quick\`."
  fi

  git checkout --quiet "release-notes/v$version"
  cat <<EOF

$version is cut at $(short "$end"), dated $day, and builds on this Mac. Its notes
are on release-notes/v$version, which is checked out:

  - write its user guide with \`just backfill docs\`, one entry at a time
  - refine its notes in $FRAGMENTS/$version/, where an overview.md goes too, and
    write a highlight about an entry with \`just backfill highlight <entry>\`
  - read the notes with \`jp release render $version\`, or as a draft page under
    \`just develop-docs\`
  - then run \`just backfill proceed\`, which finalizes $version, builds it, and
    starts the next period

\`just backfill revert $version\` takes it back, to end it on another day.
EOF
}

# File the notes of release $1, which is in preparation, and finalize it.
finish() {
  local version=$1 notes=release-notes/v$1 branch day
  branch=$(git symbolic-ref --quiet --short HEAD || true)
  if [ "$branch" = "$notes" ]; then
    clean_outside_fragments
    tidy
    git add -- "$FRAGMENTS"
    git diff --cached --quiet || git commit --quiet -m "docs(changelog): Edit the notes of $version"
  fi
  on_main
  refresh

  if git rev-parse --quiet --verify "refs/heads/$notes" >/dev/null &&
    ! git merge-base --is-ancestor "$notes" main; then
    if ! git merge --quiet --no-ff --no-edit -m "docs(changelog): File the notes of $version" "$notes"; then
      git merge --abort
      die "Merging $notes into main conflicts; merge it by hand, commit, and run \`just backfill proceed\` again."
    fi
  fi
  push_main
  # The stand-in's notes branch has to match this one, which finalize compares
  # with `main`.
  mirror

  # Edits made to the guide by hand after the last entry ship with the release.
  save_guide "$version" "docs(wiki): Edit the guide of $version"
  day=$(git show -s --format=%cs "$(start_of "$version")")
  say "Finalizing $version, dated $day."
  dated_jp "$day" release finalize "$version" >/dev/null ||
    die "Finalizing $version failed; fix what it names, then run \`just backfill proceed\` again."
  git branch --quiet -D "$notes" 2>/dev/null || true
  mirror
  clear_period
}

# Build the newest release as it ships, unless a publishable build of it is kept.
build_latest() {
  local latest
  latest=$(latest)
  [ -n "$latest" ] || return 0
  if publishable "$latest"; then
    return
  fi

  say "Building $latest for every target, as it ships; this takes a while."
  jp release build "$latest" ||
    die "$latest didn't build. Fix the build, then run \`just backfill proceed\` again, which builds $latest before it starts the next period."
}

cmd_proceed() {
  need_clone proceed
  local version left
  version=$(preparing)
  [ "$(count_of "$version")" -le 1 ] ||
    die "More than one release is in preparation: $(joined "$version")."
  if [ -z "$version" ] && [ -n "$(setting period.version)" ]; then
    die "$(setting period.version) is in drafting and not cut yet; \`just backfill cut\` cuts it."
  fi
  tools
  if [ -n "$version" ]; then
    version=$(guided_release)
    left=$(pending_items "$version" | item_labels)
    [ -z "$left" ] ||
      die "The guide of $version has parts left: $left. \`just backfill docs proceed\` commits the one in progress, \`just backfill docs\` writes the rest, and \`just backfill docs finish\` notes that they need none."
    finish "$version"
  fi
  build_latest
  cmd_next ${1+"$@"}
}

cmd_revert() {
  need_clone revert
  local target=${1:-} versions reverting version branch notes
  target=${target#v}
  [[ $target =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] ||
    die "Name the release to take back, such as \`just backfill revert 0.5.0\`."

  versions=$({ tagged; preparing; } | sort -u | newest_first)
  reverting=$(for version in $versions; do
    if at_least "$version" "$target"; then
      printf '%s\n' "$version"
    fi
  done)
  printf '%s\n' "$reverting" | grep -xF "$target" >/dev/null ||
    die "$target hasn't been cut, so there is nothing to take back."
  tools

  # Edits to notes in preparation come back with them, so commit them first.
  branch=$(git symbolic-ref --quiet --short HEAD || true)
  if [[ $branch == release-notes/v* ]]; then
    clean_outside_fragments
    git add -- "$FRAGMENTS"
    git diff --cached --quiet || git commit --quiet -m "docs(changelog): Edit the notes of ${branch#release-notes/v}"
  fi
  on_main

  for version in $reverting; do
    say "Taking back $version."
    save_guide "$version" "docs(wiki): Write the guide of $version"
    keep_guide "$version"
    forget_docs "$version"
    # `abandon` refuses a release `origin` has tagged, which here is only the
    # stand-in.
    if git ls-remote --exit-code origin "refs/tags/v$version" >/dev/null 2>&1; then
      git push --quiet origin ":refs/tags/v$version"
    fi
    jp release abandon "$version" >/dev/null || die "Taking back $version failed."
    notes=release-notes/abandon-v$version
    if git rev-parse --quiet --verify "refs/heads/$notes" >/dev/null; then
      git merge --quiet --no-ff --no-edit -m "docs(changelog): Take back the notes of $version" "$notes"
      git branch --quiet -D "$notes"
      push_main
    fi
    mirror
    remove_build "$version"
  done

  clear_period
  say "Took back $(joined "$reverting") and their builds; \`just backfill next\` starts $target's period again, with the notes as you left them, and \`just backfill docs\` brings back each release's guide and goes through its entries again."
}

cmd_draft() {
  local fresh='' after='' why='' adding='' only='' redo='' work version range from until
  local code='' wanted='' extra='' title
  while [ $# -gt 0 ]; do
    case $1 in
    --)
      shift
      break
      ;;
    --fresh)
      fresh=1
      adding=
      ;;
    --only) adding=only ;;
    --redo) adding=redo ;;
    --why)
      [ $# -ge 2 ] || die "--why takes the reason, in quotes."
      why=$2
      adding=
      shift
      ;;
    --after)
      [ $# -ge 2 ] || die "--after takes the commit whose later changes to draft."
      after=$2
      adding=
      shift
      ;;
    # The rest is for `jp query`, which refuses a flag it doesn't take either.
    -*) break ;;
    *)
      case $adding in
      # A pull request's number, without the `#` that starts a comment in fish.
      only) if [[ $1 =~ ^[0-9]{1,6}$ ]]; then only="$only#$1"$'\n'; else only="$only$1"$'\n'; fi ;;
      redo) redo="$redo$1"$'\n' ;;
      *) die "$1 follows no --only or --redo." ;;
      esac
      ;;
    esac
    shift
  done
  [ -z "$only" ] || [ -z "$redo" ] || die "--only and --redo go in separate runs."
  [ -z "$why" ] || [ -n "$only$redo" ] || die "--why goes with --only or --redo."

  if [ -n "$after" ]; then
    git rev-parse --quiet --verify "$after^{commit}" >/dev/null || die "$after names no commit."
    version="the next release"
    range="$after..HEAD"
    from=$(git show -s --format=%cs "$after")
    until=$(git show -s --format=%cs HEAD)
  else
    need_clone draft
    need_period
    version=$(setting period.version)
    [ "$(preparing)" != "$version" ] ||
      die "$version is cut already; edit its notes on release-notes/v$version, or take it back with \`just backfill revert $version\`."
    on_main
    range=$(setting period.range)
    from=$(setting period.from)
    until=$(setting period.until)
    prepare_code "$(setting period.end)"
    code=$(code_dir)
  fi
  tools

  work=$(mktemp -d)
  if [ -n "$fresh" ] && [ -n "$after" ]; then
    git restore --source=HEAD --staged --worktree -- "$FRAGMENTS"
    git clean -fdq -- "$FRAGMENTS"
    say "Discarded the uncommitted drafts in $FRAGMENTS/."
  elif [ -n "$fresh" ]; then
    discard_period
  fi
  if [ -n "$only" ]; then
    printf '%s' "$only" >"$work/wanted"
    {
      printf '## Changes to write fragments for\n\n'
      printf 'Write a fragment for each change listed below, even one you would otherwise leave out: these belong in the release notes.\n'
      if [ -n "$why" ]; then
        printf '\nThe reason given: %s\n' "$why"
      fi
    } >"$work/extra.md"
    wanted=$work/wanted
    extra=$work/extra.md
  elif [ -n "$redo" ]; then
    set_aside "$work" "$why" "$redo"
    wanted=$work/wanted
    extra=$work/extra.md
  fi

  if [ -n "$after" ]; then
    title="Draft notes after $(short "$after")"
  elif [ -n "$only" ]; then
    title="$version: draft notes for $(printf '%s' "$only" | paste -s -d ' ' -)"
  elif [ -n "$redo" ]; then
    title="$version: redraft $(printf '%s' "$redo" | sed 's|.*/||' | paste -s -d ' ' -)"
  else
    title="$version: draft notes"
  fi

  draft "$version" "$range" "$from" "$until" "$wanted" "$extra" "$code" "$title" ${1+"$@"}
  [ -z "$redo" ] || bring_back
  rm -rf "$work"
  if [ -n "$after" ]; then
    say "Review the new fragments in $FRAGMENTS/, check them with \`jp release check\`, and commit them."
  else
    period_summary
  fi
}

cmd_publish() {
  need_clone publish
  local preparing versions version missing='' github history theirs ours gap answer first last
  preparing=$(preparing)
  [ -z "$preparing" ] ||
    die "$preparing is in preparation; finish it with \`just backfill proceed\`, or take it back, first."
  [ -n "${JP_GITHUB_TOKEN:-}${GITHUB_TOKEN:-}" ] ||
    die "Publishing needs a GitHub token that can write the repository's contents, in JP_GITHUB_TOKEN or GITHUB_TOKEN; \`gh auth token\` prints one."
  on_main
  [ -z "$(git status --porcelain)" ] || die "Commit or discard the changes on main first."
  tools github
  refresh

  versions=$(tagged)
  [ -n "$versions" ] || die "No release is finalized yet, so there is nothing to publish."
  for version in $versions; do
    publishable "$version" || missing="$missing $version"
  done
  [ -z "$missing" ] ||
    die "No publishable build is kept for$missing; build each with \`jp release build <version>\` first."

  github=$(setting github)
  history=$(setting history)
  say "Fetching GitHub's main."
  git fetch --quiet --no-tags "$github" "+refs/heads/main:refs/backfill/github"
  gap=$(git rev-list --first-parent --count "$history..refs/backfill/github")
  theirs=$(git ls-remote "$github" refs/tags/v0.1.0 | cut -f1)
  ours=$(git rev-parse --quiet --verify refs/tags/v0.1.0 || true)
  first=$(printf '%s\n' "$versions" | sed -n 1p)
  last=$(printf '%s\n' "$versions" | sed -n '$p')

  cat <<EOF

This publishes $(count_of "$versions") releases, $first to $last, to $github. It:

  1. merges GitHub's main into the trial's, brings $last's user guide into it,
     and brings back the fragments of $(setting branch)
  2. deletes GitHub's old v0.1.0, when it names another commit than this one's
  3. pushes every release branch and tag in one push
  4. runs \`jp release github publish\` for each release, oldest first
  5. pushes the trial's main as the branch $HISTORY_BRANCH, for a pull request
     into main

None of it can be taken back.
EOF
  if [ "$(count_of "$versions")" -le 3 ]; then
    cat <<EOF

GitHub runs the workflows of each tagged commit when one push holds three tags
or fewer, and the history's commits deploy the site on any tag. Restrict the
\`documentation\` environment to deployments from main before going on.
EOF
  fi
  printf '\nType publish to go on: '
  IFS= read -r answer || answer=
  [ "$answer" = publish ] || die "Nothing was published."

  if ! git merge --quiet --no-edit -m "chore: Merge GitHub's \`main\` into the history to release" \
    refs/backfill/github; then
    git merge --abort
    die "Merging GitHub's main conflicts; merge it by hand with \`git merge refs/backfill/github\`, commit, and run \`just backfill publish\` again. Nothing was published."
  fi
  push_main
  guide_to_main "$last"
  restore_own

  if [ -n "$theirs" ] && [ "$theirs" != "$ours" ]; then
    say "Deleting GitHub's old v0.1.0."
    git push --quiet "$github" :refs/tags/v0.1.0
  fi
  say "Pushing the release branches and tags."
  git push --quiet "$github" 'refs/heads/release/*:refs/heads/release/*' 'refs/tags/v*:refs/tags/v*'
  for version in $versions; do
    say "Publishing $version."
    jp release github publish "$version"
  done
  say "Pushing the history's notes as $HISTORY_BRANCH."
  git push "$github" "main:refs/heads/$HISTORY_BRANCH"

  cat <<EOF

Published $first to $last on GitHub. Their notes reach GitHub's main through
$HISTORY_BRANCH: open its pull request and merge it. It brings in $(setting branch)
too, whose own fragments ship in the first release cut after it merges, with
\`just release cut\`.
EOF
  if [ "$gap" -gt 0 ]; then
    say ""
    say "$gap changes reached GitHub's main during the trial, after $(short "$history"), and have no fragments:"
    git log --first-parent --format='  %h %s' "$history..refs/backfill/github" | sed -n '1,20p'
    [ "$gap" -le 20 ] || say "  and $((gap - 20)) more"
    say "Draft them in a checkout of main once the pull request merges, with \`just backfill draft --after $(short "$history")\`, so they ship in that release too."
  fi
  say ""
  say "Then apply T-1f2jmb7's rulesets, which protect the release branches and tags."
}

main() {
  cd "$(git rev-parse --show-toplevel)"
  local command=${1:-}
  [ $# -eq 0 ] || shift
  case $command in
  init) cmd_init "$@" ;;
  next) cmd_next "$@" ;;
  draft) cmd_draft "$@" ;;
  changes) cmd_changes ;;
  cut) cmd_cut ;;
  docs) cmd_docs "$@" ;;
  highlight) cmd_highlight "$@" ;;
  proceed) cmd_proceed "$@" ;;
  revert) cmd_revert "$@" ;;
  publish) cmd_publish ;;
  *) usage ;;
  esac
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  main "$@"
  # Exit before reading further: `just backfill` runs this file from a checkout
  # that can change while a command runs, and bash reads a script as it goes.
  exit
fi
